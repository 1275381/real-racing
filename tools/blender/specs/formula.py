NAME = '方程式'
DESC = '开轮方程式：碳纤单体壳、Halo 保护环、多层前后翼'

KEYS = [
    #   y      w_low z_low  w_hip z_hip  w_belt z_belt w_roof z_roof z_crown
    K(-2.48, 0.05, 0.170, 0.075, 0.195, 0.06, 0.222, 0.025, 0.234, 0.240),
    K(-2.20, 0.09, 0.140, 0.130, 0.185, 0.11, 0.232, 0.045, 0.250, 0.258),
    K(-1.86, 0.13, 0.115, 0.185, 0.190, 0.155, 0.262, 0.065, 0.288, 0.298),
    K(-1.46, 0.19, 0.098, 0.250, 0.205, 0.215, 0.318, 0.090, 0.352, 0.364),
    K(-1.05, 0.24, 0.090, 0.300, 0.225, 0.268, 0.400, 0.120, 0.442, 0.458),
    K(-0.62, 0.27, 0.088, 0.330, 0.240, 0.300, 0.512, 0.160, 0.600, 0.628),
    K(-0.26, 0.28, 0.088, 0.345, 0.248, 0.315, 0.556, 0.190, 0.660, 0.686),
    K(0.14, 0.28, 0.088, 0.350, 0.250, 0.320, 0.578, 0.215, 0.740, 0.790),
    K(0.52, 0.275, 0.090, 0.340, 0.246, 0.306, 0.552, 0.200, 0.706, 0.740),
    K(1.02, 0.245, 0.094, 0.302, 0.236, 0.266, 0.486, 0.165, 0.590, 0.612),
    K(1.52, 0.205, 0.100, 0.252, 0.222, 0.216, 0.424, 0.125, 0.486, 0.502),
    K(2.00, 0.155, 0.112, 0.192, 0.204, 0.164, 0.364, 0.092, 0.406, 0.418),
    K(2.34, 0.105, 0.128, 0.132, 0.188, 0.112, 0.310, 0.062, 0.338, 0.346),
]

COCKPIT = zone(-0.56, 0.06, 0.0, 4.6)          # 座舱开口
SIDEIN = any_of(zone(-0.10, 0.30, 12.0, 16.0))  # 单体壳侧进气


def build():
    C.begin_car()
    ys = C.sample_ys(KEYS, 0.10, extra=(-0.56, -0.46, -0.30, -0.14, 0.06, 0.18))
    body, _ = C.build_shell(
        KEYS, ys, cap_mats=('Carbon', None),
        holes=[dict(name='Cockpit', cells=COCKPIT, mat='Interior', inset=0.075),
               dict(name='SideIntake', cells=SIDEIN, mat='Mesh', inset=0.045)])
    C.surface_strip(KEYS, -2.40, 2.30, -2.4, 2.4, 'Accent', name='StripeMid', offset=0.005)

    # ---- 车手（开轮座舱看得见）----
    C.sphere('Helmet', 0.145, (0, -0.18, 0.735), 'Accent', seg=18, ring=10, squash=0.94)
    C.plate('Visor', [(-0.34, 0.70), (-0.20, 0.755), (-0.19, 0.815), (-0.33, 0.79)],
            0.20, 'GlassDark', plane='yz')
    C.plate('Headrest', [(0.02, 0.60), (0.24, 0.60), (0.24, 0.80), (0.04, 0.80)],
            0.34, 'Interior', plane='yz')

    # ---- Halo 保护环 ----
    C.tube('HaloStrut', [(0, -0.62, 0.545), (0, -0.60, 0.70), (0, -0.575, 0.845)], 0.030, 'CarbonMat', seg=8)
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.tube('Halo' + s, [(0, -0.575, 0.855), (sx * 0.16, -0.48, 0.885), (sx * 0.27, -0.20, 0.900),
                            (sx * 0.30, 0.08, 0.855), (sx * 0.29, 0.24, 0.760)],
               0.026, 'CarbonMat', seg=8)

    # ---- 进气口 + 引擎盖 ----
    C.duct('Airbox', [(0.16, 0, 0.845, 0.115, 0.100, 2.6), (0.30, 0, 0.870, 0.135, 0.115, 2.6),
                      (0.52, 0, 0.800, 0.150, 0.105, 3.0), (0.90, 0, 0.700, 0.140, 0.085, 3.2)],
           'CarbonMat')
    C.duct('AirboxMouth', [(0.14, 0, 0.845, 0.085, 0.072, 2.6), (0.26, 0, 0.860, 0.090, 0.078, 2.6)],
           'Mesh')

    # ---- 侧箱 / 底板 ----
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.duct('Pod' + s, [(-0.28, sx * 0.42, 0.300, 0.135, 0.145, 3.0),
                           (0.10, sx * 0.47, 0.320, 0.185, 0.175, 3.2),
                           (0.62, sx * 0.44, 0.315, 0.165, 0.150, 3.2),
                           (1.10, sx * 0.36, 0.290, 0.110, 0.100, 3.0),
                           (1.44, sx * 0.28, 0.265, 0.060, 0.055, 3.0)], 'Paint')
        C.plate('PodIn' + s, [(-0.30, 0.215), (-0.26, 0.215), (-0.26, 0.430), (-0.30, 0.430)],
                0.24, 'Mesh', loc=(sx * 0.42, 0, 0), plane='yz')
        C.plate('Bargeboard' + s, [(-1.06, 0.115), (-0.62, 0.115), (-0.58, 0.400), (-1.02, 0.330)],
                0.022, 'Carbon', loc=(sx * 0.46, 0, 0), plane='yz')
    C.plate('Floor', [(-0.82, -1.10), (0.82, -1.10), (0.86, 1.30), (0.62, 1.86),
                      (-0.62, 1.86), (-0.86, 1.30)], 0.026, 'Carbon', loc=(0, 0, 0.078), plane='xy')


    # ---- 前翼 ----
    C.wing('FrontWingMain', 1.76, 0.34, 'Carbon', loc=(0, -2.34, 0.115), thick=0.024,
           camber=0.070, aoa=0.16)
    C.wing('FrontWingFlap', 1.70, 0.20, 'Carbon', loc=(0, -2.16, 0.190), thick=0.016,
           camber=0.048, aoa=0.34)
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.plate('FrontEnd' + s, [(-2.54, 0.075), (-2.02, 0.075), (-2.00, 0.335), (-2.52, 0.365)],
                0.020, 'Accent', loc=(sx * 0.88, 0, 0), plane='yz')
    # ---- 尾翼 ----
    C.wing('RearWingMain', 1.36, 0.38, 'Carbon', loc=(0, 2.06, 0.965), thick=0.028,
           camber=0.085, aoa=-0.24, gurney=0.014)
    C.wing('RearWingFlap', 1.32, 0.22, 'Carbon', loc=(0, 2.26, 1.085), thick=0.018,
           camber=0.050, aoa=-0.46)
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.plate('RearEnd' + s, [(1.80, 0.72), (2.42, 0.78), (2.42, 1.22), (1.84, 1.20)],
                0.020, 'Accent', loc=(sx * 0.68, 0, 0), plane='yz')
    C.plate('WingPylon', [(1.94, 0.42), (2.16, 0.44), (2.16, 0.96), (1.98, 0.94)],
            0.055, 'CarbonMat', plane='yz')
    C.tail_kit(KEYS,
               rain=(0.045, 0.262, 0.312, 2.352),
               exh=dict(xs=(), z=0.0, y=2.352, r=0.0),
               diff=dict(y=(1.62, 2.34), z=(0.066, 0.176), w=0.560, fins=5))
    for sx, s2 in ((1, 'L'), (-1, 'R')):          # 尾翼端板示宽灯（F1 规则件）
        C.plate('WingLamp' + s2, [(2.30, 0.86), (2.40, 0.86), (2.40, 1.06), (2.30, 1.06)],
                0.024, 'TailLight', loc=(sx * 0.685, 0, 0), plane='yz')

    # ---- 暴露的双叉臂悬架 + 排气 ----
    for sx in (1, -1):
        for ay, zz in ((C.AXLE_F, 0.255), (C.AXLE_F, 0.400), (C.AXLE_R, 0.265), (C.AXLE_R, 0.420)):
            inner = 0.24 if ay < 0 else 0.30
            C.tube('Arm%d%d%d' % (sx > 0, ay > 0, int(zz * 100)),
                   [(sx * inner, ay - 0.22, zz + 0.02), (sx * 0.55, ay - 0.05, zz),
                    (sx * 0.78, ay, zz)], 0.019, 'CarbonMat', seg=7)
            C.tube('ArmB%d%d%d' % (sx > 0, ay > 0, int(zz * 100)),
                   [(sx * inner, ay + 0.22, zz + 0.02), (sx * 0.55, ay + 0.05, zz),
                    (sx * 0.78, ay, zz)], 0.019, 'CarbonMat', seg=7)
    C.revolve('Exhaust', [(0.0, 0.046), (0.0, 0.062), (-0.20, 0.060), (-0.20, 0.0),
                          (-0.185, 0.0), (-0.185, 0.044)],
              'Chrome', seg=16, center=(0, 2.38, 0.560), axis='Y')

    C.build_wheels(dict(spokes=12, spoke_w=0.020, spoke_taper=0.8, rim_r=0.190,
                        half_w_f=0.165, half_w_r=0.195, rim_mat='RimDark',
                        cover='CarbonMat', caliper_mat='Caliper', track_out=0.030))
