# 开口：风挡 / 侧窗 / 后窗 —— 之间留出 A/B/C 柱
GLASS = any_of(zone(-0.70, -0.26, 0.0, 11.3),
               zone(-0.17, 0.56, 5.2, 11.3),
               zone(0.66, 1.02, 0.0, 11.0))
MOUTH = any_of(zone(-2.335, -2.225, 12.2, 25.0),             # 前脸大嘴
               zone(-2.30, -2.20, 9.0, 11.8))                # 两侧刹车导风口
VENTS = any_of(zone(-1.24, -1.02, 12.4, 16.6),               # 前轮后出气
               zone(0.60, 1.02, 13.0, 16.4))                 # 侧箱进气
HEADL = zone(-2.215, -2.06, 5.6, 8.6)                        # 大灯
TAILL = zone(2.235, 2.32, 8.0, 15.5)                         # 尾灯


def build():
    C.begin_car()
    ys = C.sample_ys(KEYS, 0.105, extra=(-0.30, -0.19, 0.54, 0.66, -0.74,
                                     -2.315, -2.29, -2.26, -2.22, -2.18, -2.14, -2.10, -2.05,
                                     2.18, 2.24, 2.30, 2.36, 2.385, 2.41, 2.425, 2.44))
    body, _ = C.build_shell(
        KEYS, ys,
        arches=[dict(y=C.AXLE_F, r=0.455, dz=0.03), dict(y=C.AXLE_R, r=0.470, dz=0.03)],
        cap_mats=('Carbon', None),
        holes=[
            dict(name='Glass', cells=GLASS, mat='GlassDark', inset=0.016),
            dict(name='Mouth', cells=MOUTH, mat='Mesh', inset=0.085),
            dict(name='Vents', cells=VENTS, mat='Mesh', inset=0.060),
            dict(name='LampLens', cells=HEADL, mat='GlassDark', inset=0.022),
        ])

    for sx, s in ((1, 'L'), (-1, 'R')):                        # 灯罩内部的发光灯条
        C.surface_strip(KEYS, -2.20, -2.075, sx * 6.1, sx * 8.1, 'HeadLight',
                        name='HeadLight' + s, offset=-0.040, steps=3)

    # ---- 车顶双色条 + 钣金分缝 + 引擎盖散热百叶 ----
    C.surface_strip(KEYS, -2.10, 2.30, -1.6, 1.6, 'Accent', name='StripeMid', offset=0.005)
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.surface_strip(KEYS, -2.10, 2.30, sx * 2.4, sx * 4.0, 'Accent', name='Stripe' + s, offset=0.005)
        for k in range(4):                                     # 前盖散热百叶
            y0 = -1.42 + k * 0.135
            C.surface_strip(KEYS, y0, y0 + 0.055, sx * 2.6, sx * 7.6, 'CarbonMat',
                            name='Louver%s%d' % (s, k), offset=0.004, steps=3)
    for y in (-1.66, -0.80):                                   # 钣金分缝线
        C.surface_strip(KEYS, y, y + 0.014, -12.4, 12.4, 'CarbonMat',
                        name='Shut%.0f' % (y * 100), offset=0.003, steps=2)

    # ---- 前分流板 / 定风翼 ----
    C.plate('Splitter', [(-0.94, -1.95), (0.94, -1.95), (0.88, -2.34), (0.46, -2.50),
                         (-0.46, -2.50), (-0.88, -2.34)], 0.032, 'Carbon', loc=(0, 0, 0.078), plane='xy')
    for sx, s in ((1, 'L'), (-1, 'R')):                        # 前保险杠定风翼（水平刀翼）
        for (zz, y0, x0, x1) in ((0.40, -2.06, 0.56, 0.90), (0.515, -2.00, 0.52, 0.84)):
            C.plate('Canard%s%d' % (s, int(zz * 100)),
                    [(sx * x0, y0 + 0.10), (sx * x1, y0 - 0.02), (sx * x1, y0 - 0.10),
                     (sx * x0, y0 - 0.02)], 0.028, 'Carbon', loc=(0, 0, zz), plane='xy')
    C.plate('SkirtL', [(-1.24, 0.0), (1.30, 0.0), (1.30, 0.11), (-1.24, 0.11)],
            0.05, 'Carbon', loc=(0.885, 0, 0.088), plane='yz')
    C.plate('SkirtR', [(-1.24, 0.0), (1.30, 0.0), (1.30, 0.11), (-1.24, 0.11)],
            0.05, 'Carbon', loc=(-0.885, 0, 0.088), plane='yz')

    # ---- 后扩散器 ----
    # ---- 鹅颈尾翼 ----
    C.wing('WingPlane', 1.66, 0.40, 'Carbon', loc=(0, 2.02, 1.30), thick=0.028,
           camber=0.085, aoa=-0.24, gurney=0.016)
    for sx in (1, -1):
        C.plate('WingEnd%s' % ('L' if sx > 0 else 'R'),
                [(1.74, 1.06), (2.32, 1.13), (2.32, 1.44), (1.80, 1.46), (1.72, 1.30)],
                0.020, 'Carbon', loc=(sx * 0.83, 0, 0), plane='yz')
        C.plate('WingPylon%s' % ('L' if sx > 0 else 'R'),
                [(1.86, 0.70), (2.10, 0.70), (2.12, 1.28), (1.92, 1.30)],
                0.034, 'Carbon', loc=(sx * 0.34, 0, 0), plane='yz')

    # ---- 车顶进气 / 引擎盖散热百叶 ----
    C.plate('RoofScoop', [(-0.40, 1.010), (0.10, 1.120), (0.10, 1.235), (-0.34, 1.150)],
            0.30, 'Carbon', loc=(0, 0, 0), plane='yz')
    C.plate('RoofScoopIn', [(-0.34, 1.055), (0.06, 1.140), (0.06, 1.205), (-0.30, 1.130)],
            0.22, 'Mesh', loc=(0, 0, 0), plane='yz')

    # ---- 后视镜 / 排气 / 拖车钩 ----
    for sx in (1, -1):
        s = 'L' if sx > 0 else 'R'
        C.tube('MirrorArm' + s, [(sx * 0.72, -0.50, 0.845), (sx * 0.88, -0.55, 0.885),
                                 (sx * 0.99, -0.57, 0.935)], 0.019, 'Carbon', seg=8)
        C.plate('Mirror' + s, [(-0.64, 0.895), (-0.48, 0.915), (-0.48, 1.005), (-0.64, 0.985)],
                0.075, 'Paint', loc=(sx * 1.01, 0, 0), plane='yz')
    # ---- 车尾套件（玩家全程盯着的画面，层次照量产跑车排）----
    C.tail_kit(
        KEYS,
        lip=(2.330, 2.372, 12.4),                       # 鸭尾压线
        bar=(0.600, 0.598, 0.652, 2.452),               # 尾面贯穿灯带（嵌在暗色带里）
        wrap=(2.245, 2.442, 11.8, 13.2),                # 灯带绕到两侧翼子板
        valance=(1.90, 2.44, 16.4, 28.0),               # 下包围
        rain=(0.050, 0.500, 0.536, 2.450),
        badge=(0.120, 0.440, 0.468, 2.450),
        exh=dict(xs=(0.425, 0.545), z=0.296, y=2.470, r=0.044,
                 box=(0.630, 0.205, 0.404)),            # 下包围（凸出尾面）
        lic=(0.238, 0.248, 0.362, 2.496),
        vents=(0.038, 0.318, 0.252, 0.358, 2.496),
        diff=dict(y=(1.78, 2.50), z=(0.086, 0.208), w=0.800, fins=7))

    C.build_wheels(dict(spokes=10, spoke_w=0.026, rim_r=0.206, half_w_f=0.150, half_w_r=0.176,
                        rim_mat='RimDark', caliper_mat='Caliper', track_out=0.022))
