DESC = '美式房车赛：方正宽体、增压进气罩、刀片尾翼、侧出排气'

KEYS = [
    #   y      w_low z_low  w_hip z_hip  w_belt z_belt w_roof z_roof z_crown
    K(-2.42, 0.52, 0.212, 0.72, 0.320, 0.700, 0.560, 0.44, 0.640, 0.660),
    K(-2.32, 0.60, 0.180, 0.80, 0.325, 0.782, 0.590, 0.52, 0.672, 0.690),
    K(-2.10, 0.66, 0.158, 0.862, 0.335, 0.846, 0.640, 0.60, 0.724, 0.740),
    K(-1.80, 0.69, 0.150, 0.902, 0.345, 0.888, 0.690, 0.65, 0.776, 0.790),
    K(-1.46, 0.70, 0.148, 0.918, 0.350, 0.905, 0.722, 0.68, 0.812, 0.824),
    K(-1.05, 0.71, 0.148, 0.912, 0.352, 0.900, 0.760, 0.70, 0.856, 0.868),
    K(-0.66, 0.715, 0.148, 0.914, 0.352, 0.902, 0.812, 0.72, 0.912, 0.926),
    K(-0.46, 0.715, 0.148, 0.914, 0.352, 0.900, 0.856, 0.70, 1.060, 1.106),
    K(-0.16, 0.715, 0.148, 0.916, 0.352, 0.898, 0.876, 0.675, 1.238, 1.288),
    K(0.16, 0.715, 0.148, 0.918, 0.352, 0.896, 0.882, 0.665, 1.288, 1.336),
    K(0.56, 0.715, 0.150, 0.920, 0.352, 0.896, 0.878, 0.660, 1.282, 1.330),
    K(0.88, 0.715, 0.152, 0.922, 0.352, 0.898, 0.866, 0.630, 1.226, 1.268),
    K(1.16, 0.715, 0.156, 0.926, 0.352, 0.904, 0.842, 0.560, 1.086, 1.116),
    K(1.44, 0.71, 0.160, 0.930, 0.352, 0.908, 0.820, 0.520, 0.966, 0.984),
    K(1.86, 0.705, 0.168, 0.922, 0.348, 0.902, 0.796, 0.510, 0.912, 0.926),
    K(2.24, 0.67, 0.182, 0.882, 0.340, 0.862, 0.762, 0.500, 0.868, 0.880),
    K(2.44, 0.62, 0.200, 0.812, 0.332, 0.796, 0.740, 0.470, 0.840, 0.850),
]

GLASS = any_of(zone(-0.62, -0.22, 0.0, 11.4),
               zone(-0.14, 0.86, 4.8, 11.4),
               zone(0.94, 1.24, 0.0, 11.0))
GRILLE = any_of(zone(-2.415, -2.30, 11.5, 22.0))
HEADL = zone(-2.40, -2.30, 6.5, 10.5)
VENTS = zone(-1.24, -1.06, 13.0, 16.5)


def build():
    C.begin_car()
    ys = C.sample_ys(KEYS, 0.105, extra=(-2.40, -2.36, -2.32, -2.28, -0.62, -0.22,
                                         -0.14, 0.86, 0.94, 1.24, 2.36))
    body, _ = C.build_shell(
        KEYS, ys, squash=0.10,
        arches=[dict(y=C.AXLE_F, r=0.470, dz=0.05), dict(y=C.AXLE_R, r=0.480, dz=0.05)],
        cap_mats=('CarbonMat', None),
        holes=[
            dict(name='Glass', cells=GLASS, mat='GlassDark', inset=0.016),
            dict(name='Grille', cells=GRILLE, mat='Mesh', inset=0.070),
            dict(name='Vents', cells=VENTS, mat='Mesh', inset=0.050),
            dict(name='LampLens', cells=HEADL, mat='GlassDark', inset=0.022),
        ])
    # 四圆灯 + 车身色带
    for sx, s in ((1, 'L'), (-1, 'R')):
        for k, (x0, r) in enumerate(((0.36, 0.085), (0.56, 0.085))):
            C.revolve('HeadLamp%s%d' % (s, k),
                      [(0.0, 0.0), (0.0, r), (0.045, r * 0.92), (0.045, 0.0)], 'HeadLight',
                      seg=16, center=(sx * x0, -2.395, 0.660), axis='Y')
        C.surface_strip(KEYS, -2.34, 2.40, sx * 2.2, sx * 5.4, 'Accent',
                        name='Stripe' + s, offset=0.005)
    C.surface_strip(KEYS, -2.30, 2.40, 13.6, 15.4, 'Accent', name='StripeSideL', offset=0.004)
    C.surface_strip(KEYS, -2.30, 2.40, -15.4, -13.6, 'Accent', name='StripeSideR', offset=0.004)
    for y in (-1.70, -0.74):
        C.surface_strip(KEYS, y, y + 0.016, -12.0, 12.0, 'CarbonMat',
                        name='Shut%.0f' % (y * 100), offset=0.003, steps=2)

    # ---- 机械增压进气罩 ----
    C.duct('Blower', [(-1.52, 0, 0.865, 0.19, 0.055, 3.2), (-1.30, 0, 0.930, 0.23, 0.105, 3.0),
                      (-1.02, 0, 0.945, 0.235, 0.115, 3.0), (-0.86, 0, 0.905, 0.20, 0.075, 3.2)],
           'CarbonMat')
    C.duct('BlowerMouth', [(-1.56, 0, 0.870, 0.145, 0.040, 3.0), (-1.42, 0, 0.900, 0.16, 0.055, 3.0)],
           'Mesh')

    # ---- 前唇 / 侧裙 / 刀片尾翼 ----
    C.plate('ChinSpoiler', [(-0.90, -2.20), (0.90, -2.20), (0.86, -2.52), (-0.86, -2.52)],
            0.052, 'CarbonMat', loc=(0, 0, 0.150), plane='xy')
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.plate('Skirt' + s, [(-1.16, 0.0), (1.24, 0.0), (1.24, 0.115), (-1.16, 0.115)],
                0.055, 'CarbonMat', loc=(sx * 0.905, 0, 0.135), plane='yz')
        C.plate('SpoilerUp' + s, [(2.10, 0.845), (2.32, 0.828), (2.32, 1.045), (2.10, 1.060)],
                0.040, 'CarbonMat', loc=(sx * 0.60, 0, 0), plane='yz')
        for k in range(4):                        # 侧排气
            C.revolve('Exh%s%d' % (s, k), [(0.0, 0.0), (0.0, 0.046), (0.10 * sx, 0.044), (0.10 * sx, 0.0)],
                      'Chrome', seg=12, center=(sx * 0.90, -0.30 + 0.24 * k, 0.235), axis='X')
    C.plate('Spoiler', [(2.06, 1.020), (2.40, 1.000), (2.40, 1.078), (2.06, 1.098)],
            1.60, 'CarbonMat', plane='yz')
    # ---- 车尾套件：整面式分段尾灯（美式房车的招牌）----
    C.tail_kit(
        KEYS,
        lip=(2.330, 2.386, 12.6),
        bar=(0.700, 0.606, 0.664, 2.452), bar_seg=6,
        wrap=(2.240, 2.442, 11.6, 13.2),
        valance=(1.90, 2.44, 17.0, 28.0),
        badge=(0.130, 0.520, 0.552, 2.450),
        rain=(0.048, 0.520, 0.552, 2.450),
        exh=dict(xs=(), z=0.300, y=2.452, r=0.048, box=(0.740, 0.196, 0.386)),
        lic=(0.262, 0.240, 0.360, 2.496),
        vents=(0.060, 0.430, 0.238, 0.362, 2.496),
        refl=(0.640, 0.226, 0.286, 2.496),
        diff=dict(y=(1.96, 2.56), z=(0.140, 0.244), w=0.780, fins=6))
    for sx, s in ((1, 'L'), (-1, 'R')):
        C.tube('MirrorArm' + s, [(sx * 0.80, -0.56, 0.905), (sx * 0.94, -0.60, 0.945)],
               0.022, 'CarbonMat', seg=8)
        C.plate('Mirror' + s, [(-0.68, 0.920), (-0.50, 0.940), (-0.50, 1.040), (-0.68, 1.020)],
                0.080, 'Paint', loc=(sx * 0.97, 0, 0), plane='yz')
    C.plate('TowHook', [(-2.56, 0.30), (-2.44, 0.30), (-2.44, 0.36), (-2.56, 0.36)],
            0.06, 'Accent', loc=(0.42, 0, 0), plane='yz')

    C.build_wheels(dict(spokes=5, spoke_w=0.062, spoke_taper=0.85, rim_r=0.198,
                        half_w_f=0.170, half_w_r=0.196, rim_mat='RimAlloy',
                        caliper_mat='Steel', center_lock=False, grooves=2, track_out=0.014))
