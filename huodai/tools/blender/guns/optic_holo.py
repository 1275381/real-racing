"""全息瞄准镜（EOTech EXPS3 形态，×1.2）：快拆座 + 电池下壳 + 矩形护罩 + 前后窗。"""
import gun_kit as K
from gun_kit import Group, side, xsec, top, box, cyl, cut, cutter_box
from _optic_common import rail_clamp

META = dict(ref=(0.0, 0.0, 0.0), target=(0.0, 0.0, 0.0), length=None, size=1024)


def build():
    rail_clamp(-0.07, -0.01, half_w=0.022, bolt_z=-0.055)
    # 右侧快拆扳把
    side("qd_lever", [(-0.06, -0.001), (-0.022, 0.001, 0.003), (-0.02, 0.006, 0.003), (-0.058, 0.006, 0.002)],
         0.0222, 0.026, "alu", bevel=0.0006)
    # 下壳（电池仓 + 激光器）
    body = top("body", [(-0.025, 0.012, 0.004), (0.025, 0.012, 0.004), (0.025, -0.098, 0.006), (-0.025, -0.098, 0.006)],
               0.004, 0.033, "alu", bevel=0.0018)
    # 电池仓盖（左侧横置）
    cyl("battery_cap", (-0.0262, 0.019, -0.075), 0.0085, 0.004, "alu", axis="x", segs=24)
    # 护罩：顶梁 + 两侧墙（中空方框，前后通透），后部高出的激光器罩
    g = Group()
    g.xsec([(-0.0325, 0.0705), (0.0325, 0.0705), (0.0325, 0.077, 0.003), (-0.0325, 0.077, 0.003)], -0.1, -0.03)
    for sx in (-1, 1):
        g.xsec([(sx * 0.0255, 0.03), (sx * 0.0325, 0.03), (sx * 0.0325, 0.0715), (sx * 0.0255, 0.0715)], -0.1, -0.03)
    g.done("hood", "alu", bevel=0.0012)
    # 护罩侧墙减重窗
    hood = K.PARTS[-1]
    for sx in (-1, 1):
        cut(hood, cutter_box("hood_win%d" % sx, (sx * 0.029, 0.05, -0.065), (0.012, 0.022, 0.044), r=0.004))
    # 前窗 / 后窗边框（窗本体留空，ADS 透过去看）
    g = Group()
    for z in (-0.099, -0.031):
        g.xsec([(-0.0255, 0.033), (0.0255, 0.033), (0.0255, 0.036), (-0.0255, 0.036)], z - 0.001, z + 0.001)
    g.done("window_sills", "alu", bevel=0.0004)
    box("laser_house", (0.0, 0.045, -0.012), (0.03, 0.024, 0.04), "alu", bevel=0.003)
    # 后端按键（上/下/夜视）
    g = Group()
    for x in (-0.012, 0.0, 0.012):
        g.cyl((x, 0.023, 0.0135), 0.0038, 0.004, axis="z", segs=16)
    g.done("buttons", "rubber", bevel=0.001)
    # 前窗镀膜反光片（极窄，只在边缘露出一圈）
    box("front_glass_edge", (0.0, 0.0525, -0.1), (0.05, 0.035, 0.0006), "lens", bevel=0.0)
