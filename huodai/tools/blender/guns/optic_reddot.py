"""大窗开放式反射红点镜（Holosun 510C 形态，窗 60×45 mm 为游戏放大窗）。
玻璃片与内投影红点由游戏代码生成（透明玻璃 + 自发光点）；这里只做镜体，
且全件不高于窗顶（y=0.069）—— ADS 瞄准线换算依赖「窗顶 = 全镜最高点」。"""
import gun_kit as K
from gun_kit import Group, side, top, box, cyl
from _optic_common import rail_clamp

META = dict(ref=(0.0, 0.0, 0.0), target=(0.0, 0.0, 0.0), length=None, size=1024)

WIN_Z = -0.058
WIN_B = 0.024
WIN_T = 0.069


def build():
    rail_clamp(-0.064, 0.004, half_w=0.021, bolt_z=-0.03)
    # 底座：后窄前宽的整体外壳（俯视梯形），y 0.004..0.024
    top("housing", [(-0.0215, 0.006, 0.006), (0.0215, 0.006, 0.006), (0.0345, -0.046, 0.004), (0.0345, -0.067, 0.004),
                    (-0.0345, -0.067, 0.004), (-0.0345, -0.046, 0.004)], 0.004, WIN_B, "alu", bevel=0.0012)
    # 窗两侧立柱（后掠，矮于窗顶 2 mm）
    g = Group()
    for sx in (-1, 1):
        g.side([(-0.067, WIN_B - 0.001), (-0.049, WIN_B - 0.001), (-0.052, 0.04, 0.006), (-0.0565, WIN_T - 0.002, 0.002),
                (-0.0625, WIN_T - 0.002, 0.002), (-0.066, 0.045, 0.004)],
               sx * 0.0302 if sx > 0 else -0.0345, 0.0345 if sx > 0 else -0.0302)
    g.done("posts", "alu", bevel=0.0009)
    # 内红点发射器（玻璃后方）+ 发射窗
    box("emitter", (0.0, WIN_B + 0.0045, -0.03), (0.017, 0.009, 0.02), "alu", bevel=0.0015)
    box("emitter_lens", (0.0, WIN_B + 0.005, -0.0402), (0.007, 0.004, 0.0008), "lens", bevel=0.0)
    # 右侧风偏 / 顶后高低调节塔 + 左侧 +/- 按键 + 右侧电池仓
    cyl("windage", (0.0235, 0.015, -0.012), 0.0042, 0.004, "alu", axis="x", segs=20)
    cyl("elev", (0.0, WIN_B + 0.002, -0.008), 0.0045, 0.004, "alu", axis="y", segs=20)
    g = Group()
    for z in (-0.032, -0.02):
        g.box((-0.0222, 0.015, z), (0.003, 0.006, 0.008))
    g.done("buttons", "rubber", bevel=0.0012)
    box("battery_tray", (0.0222, 0.0145, -0.038), (0.0024, 0.012, 0.02), "alu", bevel=0.0008)
    # 前端遮光檐（窗下沿前唇）
    box("front_lip", (0.0, WIN_B + 0.0015, -0.0655), (0.066, 0.003, 0.004), "alu", bevel=0.0008)
