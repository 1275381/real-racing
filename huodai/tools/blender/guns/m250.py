def pouch():
    """100 发软弹袋（OD 尼龙）：挂在机匣左下，鼓肚圆角盒 + 顶盖翻片 + 织带 + 包边 + 挂架"""
    x0, x1 = -0.0560, 0.0100
    z0, z1 = -0.1000, -0.2060
    y0, y1 = RB - 0.0080, -0.1700
    xc, zc = (x0 + x1) * 0.5, (z0 + z1) * 0.5
    hx, hz = (x1 - x0) * 0.5, (z0 - z1) * 0.5
    p = side("pouch", [(z0, y0, 0.010), (z1, y0, 0.010), (z1, y1, 0.016), (z0, y1, 0.016)], x0, x1, "poly_od",
             bevel=0.0040, segs=3)

    def bulge(x, y, z):
        t = (y0 - y) / (y0 - y1)                    # 0 顶 → 1 底
        b = math.sin(math.pi * min(1.0, max(0.0, t))) * 0.10 + 0.02 * t
        return (xc + (x - xc) * (1.0 + b), y, zc + (z - zc) * (1.0 + b * 0.5))
    deform(p, bulge)
    # 顶盖翻片（略大一圈，前沿垂下一截）
    side("pouch_flap", [(z0 + 0.0040, y0 + 0.0030, 0.006), (z1 - 0.0040, y0 + 0.0030, 0.006), (z1 - 0.0040, y0 - 0.0160, 0.004),
                        (z1 + 0.0060, y0 - 0.0170, 0.004), (z1 + 0.0060, y0 - 0.0040), (z0 + 0.0040, y0 - 0.0040)],
         x0 - 0.0030, x1 + 0.0030, "poly_od", bevel=0.0020, segs=2)
    # 织带（MOLLE 横带，外侧 + 前后面）+ 竖向包边
    g = Group()
    for k in range(3):
        yy = y0 - 0.0450 - k * 0.0300
        g.side([(z0 - 0.0060, yy + 0.0060), (z1 + 0.0060, yy + 0.0060), (z1 + 0.0060, yy - 0.0060),
                (z0 - 0.0060, yy - 0.0060)], x0 - 0.0035, x0 + 0.0005)
    for k in range(2):                    # 右侧面两道横带
        yy = y0 - 0.0600 - k * 0.0400
        g.side([(z0 - 0.0100, yy + 0.0055), (z1 + 0.0100, yy + 0.0055), (z1 + 0.0100, yy - 0.0055),
                (z0 - 0.0100, yy - 0.0055)], x1 - 0.0005, x1 + 0.0030)
    for zz in (z0 - 0.0060, z1 + 0.0060):
        g.side([(zz + 0.0030, y0 - 0.0200), (zz - 0.0030, y0 - 0.0200), (zz - 0.0030, y1 + 0.0150),
                (zz + 0.0030, y1 + 0.0150)], x0 - 0.0025, x0 + 0.0005)
    deform(g.done("pouch_webbing", "poly_od", bevel=0.0006), bulge)
    # 翻片快扣（黑塑料）
    g = Group()
    g.side([(zc + 0.0110, y0 - 0.0060), (zc - 0.0110, y0 - 0.0060), (zc - 0.0090, y0 - 0.0300, 0.003),
            (zc + 0.0090, y0 - 0.0300, 0.003)], x0 - 0.0055, x0 - 0.0015)
    deform(g.done("pouch_buckle", "poly", bevel=0.0006), bulge)
    # 挂架（机匣底下的铝挂板 + 左侧挂钩）
    g = Group()
    g.xsec([(x0 + 0.0080, RB - 0.0080), (0.0080, RB - 0.0080), (0.0080, RB + 0.0010), (x0 + 0.0080, RB + 0.0010)],
           z0 - 0.0040, z1 + 0.0040)
    g.done("pouch_bracket", "alu", bevel=0.0006)


