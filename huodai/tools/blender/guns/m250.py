def grip():
    def lerp(a, b, t):
        return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    f0, f1 = (-0.0500, LB + 0.0005), (-0.0150, -0.1310)
    r0, r1 = (-0.0100, LB + 0.0005), (0.0210, -0.1190)
    pts = []
    n = 10
    for k in range(n + 1):
        t = k / n
        z, y = lerp(r0, r1, t)
        z += 0.0040 * math.sin(math.pi * t) - 0.0030 * math.exp(-((t - 0.12) / 0.07) ** 2)
        pts.append((z, y, 0.006) if k == n else (z, y))
    for k in range(n + 1):
        t = 1.0 - k / n
        z, y = lerp(f0, f1, t)
        z -= 0.0042 * math.exp(-((t - 0.42) / 0.10) ** 2) - 0.0014 * math.sin(math.pi * t)
        pts.append((z, y, 0.005) if k == 0 else (z, y))
    gp = side("grip", pts, -0.0135, 0.0135, "poly", bevel=0.0035, segs=3)
    taper_x(gp, -0.055, 0.028, 0.80, 1.0)
    c0 = ((f0[0] + r0[0]) * 0.5, (f0[1] + r0[1]) * 0.5)
    c1 = ((f1[0] + r1[0]) * 0.5, (f1[1] + r1[1]) * 0.5)
    L = math.hypot(c1[0] - c0[0], c1[1] - c0[1])
    ax = ((c1[0] - c0[0]) / L, (c1[1] - c0[1]) / L)
    pp = (-ax[1], ax[0]) if -ax[1] > 0 else (ax[1], -ax[0])
    g = Group()
    for sx in (-1, 1):
        for i in range(13):
            s = 0.024 + i * 0.0042
            a = (c0[0] + ax[0] * s, c0[1] + ax[1] * s)
            p0 = (a[0] - pp[0] * 0.0085, a[1] - pp[1] * 0.0085)
            p1 = (a[0] + pp[0] * 0.0115, a[1] + pp[1] * 0.0115)
            h = 0.0011
            poly = [(p0[0] + ax[0] * h, p0[1] + ax[1] * h), (p1[0] + ax[0] * h, p1[1] + ax[1] * h),
                    (p1[0] - ax[0] * h, p1[1] - ax[1] * h), (p0[0] - ax[0] * h, p0[1] - ax[1] * h)]
            xx = 0.0135 * (0.80 + 0.20 * min(1.0, max(0.0, (a[0] + 0.055) / 0.083)))
            g.side(poly, sx * (xx - 0.0003), sx * (xx + 0.0006))
    g.done("grip_ribs", "poly", bevel=0.0)


