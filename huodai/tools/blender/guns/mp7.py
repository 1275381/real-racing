# ---------------- 小工具 ----------------

def loft_bm(bm, secs, cap=(True, True)):
    rings = [[bm.verts.new(B(p[0], p[1], z)) for p in pts] for z, pts in secs]
    n = len(rings[0])
    for a, b in zip(rings, rings[1:]):
        for j in range(n):
            j2 = (j + 1) % n
            bm.faces.new((a[j], a[j2], b[j2], b[j]))
    if cap[0]:
        bm.faces.new(rings[0][::-1])
    if cap[1]:
        bm.faces.new(rings[-1])


def loft(name, secs, zone, **kw):
    bm = bmesh.new()
    loft_bm(bm, secs)
    return K.obj(name, bm, zone, **kw)


def revolve_bm(bm, prof, c, axis="z", segs=24):
    rings = []
    for i in range(segs):
        a = 2 * math.pi * i / segs
        ca, sa = math.cos(a), math.sin(a)
        ring = []
        for t, r in prof:
            if axis == "z":
                p = (c[0] + r * ca, c[1] + r * sa, c[2] + t)
            elif axis == "x":
                p = (c[0] + t, c[1] + r * ca, c[2] + r * sa)
            else:
                p = (c[0] + r * ca, c[1] + t, c[2] + r * sa)
            ring.append(bm.verts.new(B(*p)))
        rings.append(ring)
    m = len(prof)
    for i in range(segs):
        r0, r1 = rings[i], rings[(i + 1) % segs]
        for j in range(m):
            j2 = (j + 1) % m
            bm.faces.new((r0[j], r0[j2], r1[j2], r1[j]))


def pyramid_bm(bm, pts, x0, x1):
    vs = [bm.verts.new(B(x0, y, z)) for z, y in pts]
    cz = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    ap = bm.verts.new(B(x1, cy, cz))
    n = len(vs)
    for i in range(n):
        bm.faces.new((vs[i], vs[(i + 1) % n], ap))
    bm.faces.new(vs[::-1])


def rr_sec(hw, top_, bot, rt, rb, n=5, xc=0.0):
    pts = []
    for cx, cy, r, a0 in ((hw - rb, bot + rb, rb, -90), (hw - rt, top_ - rt, rt, 0),
                          (-hw + rt, top_ - rt, rt, 90), (-hw + rb, bot + rb, rb, 180)):
        for k in range(n + 1):
            a = math.radians(a0 + 90 * k / n)
            pts.append((xc + cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def rail_bm(bm, z0, z1, conv):
    """皮卡汀尼导轨（任意朝向）：conv(u, v) → (x, y)，u 横向、v 朝外高度"""
    def P(pts):
        return [conv(u, v) for u, v in pts]
    xsec_pts = P([(-0.0078, 0.0), (0.0078, 0.0), (0.0078, 0.0035), (-0.0078, 0.0035)])
    K.xsec_bm(bm, xsec_pts, z0, z1)
    tooth = P([(-0.0078, 0.0025), (0.0078, 0.0025), (0.0106, 0.0045), (0.0106, 0.0057), (0.0095, 0.0066),
               (-0.0095, 0.0066), (-0.0106, 0.0057), (-0.0106, 0.0045)])
    n = int((z1 - z0 - 0.002) / 0.01)
    off = (z1 - z0 - n * 0.01) * 0.5
    for k in range(n):
        za = z0 + off + k * 0.01 + 0.0026
        K.xsec_bm(bm, tooth, za, za + 0.0048)


def stipple(g, a0, a1, half_w, hw_fn, st=0.0036, d=0.0015, h=0.0007, sides=(-1, 1)):
    """斜置面板上的棱锥防滑点阵：a0→a1 为面板中线（侧视 z, y），half_w 面板半宽"""
    du = (a1[0] - a0[0], a1[1] - a0[1])
    L = math.hypot(*du)
    u = (du[0] / L, du[1] / L)
    v = (-u[1], u[0])
    rows = int(L / (st * 0.6)) + 1
    for i in range(rows):
        cu = i * st * 0.6
        off = 0.5 * st if i % 2 else 0.0
        for j in range(-8, 9):
            cv = j * st + off
            if abs(cv) > half_w:
                continue
            c = (a0[0] + u[0] * cu + v[0] * cv, a0[1] + u[1] * cu + v[1] * cv)
            dd = d * 1.2
            dia = [(c[0] + u[0] * dd, c[1] + u[1] * dd), (c[0] + v[0] * d, c[1] + v[1] * d),
                   (c[0] - u[0] * dd, c[1] - u[1] * dd), (c[0] - v[0] * d, c[1] - v[1] * d)]
            hw = hw_fn(c[0], c[1])
            for sx in sides:
                pyramid_bm(g.bm, dia, sx * (hw - 0.0002), sx * (hw + h))


