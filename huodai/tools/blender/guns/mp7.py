def magazine():
    # 弹匣沿握把倾角（约 7°）向下：前后沿直线
    def zr(y, base):
        return base + (y + 0.13) * (-0.15)
    yt, yb = -0.128, -0.2185
    pts = [(zr(yt, -0.1185), yt), (zr(yt, -0.1585), yt), (zr(yb, -0.1600), yb, 0.002), (zr(yb, -0.1170), yb, 0.002)]
