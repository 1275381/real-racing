"""Thompson M1928A1（.45 ACP，烤蓝铣削机匣 + 胡桃木枪托 / 后握把 / "芝加哥打字机"竖前握把，
散热片枪管 + Cutts 补偿器，30 发直弹匣）。

真实尺寸建模（米）：原点 z=0 = 机匣后端面，y=0 = 枪膛轴线；全长 0.852 m
（补偿器前缘 z=-0.570 → 托底板 z=+0.282）。
机匣顶面：后端 Lyman 可调表尺、中间拉机柄滑槽 + 顶置拉机柄；右侧抛壳窗；
左侧快慢机 + 保险两根拨杆；扳机座（下机匣）挂在机匣后半段下方，带后握把与扳机护圈；
弹匣竖直插在扳机护圈正前方。
"""
import math

import gun_kit as K
from gun_kit import Group, side, xsec, lathe, box, cyl, cut, cutter_box, taper_x, deform

# 后握把顶后缘（虎口位，扳机座下沿）→ 程序化汤姆逊 grip；整枪缩到程序化长度
META = dict(ref=(0.0, -0.057, -0.036), target=(0.0, -0.041, 0.1303), length=0.847)

RX = 0.0165          # 机匣半宽
RT = 0.021           # 机匣顶面
RB = -0.034          # 机匣底面
FB = -0.056          # 扳机座底面
RF = -0.274          # 机匣前端
MZ = (-0.144, -0.179)   # 弹匣后/前面


def ring_bm(bm, c, R, a, n=16, m=8):
    """侧面可见的圆环（环面法线沿 x）：背带环用"""
    prof = [(c[0] + a * math.cos(2 * math.pi * k / m), R + a * math.sin(2 * math.pi * k / m)) for k in range(m + 1)]
    K.lathe_bm(bm, prof, cx=c[1], cy=c[2], segs=n, axis="x")


def receiver():
    rec = side("receiver", [(0.0, RB), (0.0, RT - 0.004, 0.003), (-0.004, RT, 0.003), (RF + 0.006, RT, 0.004),
                            (RF, RT - 0.006, 0.004), (RF, RB + 0.003, 0.002), (RF + 0.004, RB)],
               -RX, RX, "steel", bevel=0.0012)
    # 顶面上沿倒大圆角（铣削机匣的圆顶）——两条斜切
    for sx in (-1, 1):
        bm = K.bmesh.new()
        K.xsec_bm(bm, [(sx * RX, RT - 0.0055), (sx * (RX + 0.01), RT - 0.0055), (sx * (RX + 0.01), RT + 0.01),
                       (sx * (RX - 0.0055), RT + 0.01)], 0.01, RF - 0.01)
        cut(rec, K.obj("chamf%d" % sx, bm, None, cutter=True))
    # 顶面拉机柄滑槽、右侧抛壳窗
    cut(rec, cutter_box("act_slot", (0.0, RT, -0.15), (0.0062, 0.01, 0.15), r=0.003))
    cut(rec, cutter_box("ejport", (RX, 0.004, -0.165), (0.008, 0.019, 0.062), r=0.002))
    box("bolt", (0.007, 0.004, -0.165), (0.016, 0.019, 0.062), "steel", bevel=0.0008)
    box("bolt_face", (RX - 0.004, 0.004, -0.19), (0.0016, 0.008, 0.012), "bore", bevel=0.0)
    box("slot_dark", (0.0, RT - 0.004, -0.15), (0.0058, 0.002, 0.148), "bore", bevel=0.0)
    # 顶置拉机柄（枪机闭锁位：滑槽前端）：立柱 + 滚花圆钮
    g = Group()
    g.box((0.0, RT + 0.002, -0.215), (0.006, 0.01, 0.012))
    g.lathe([(RT + 0.004, 0.0001), (RT + 0.004, 0.0072), (RT + 0.006, 0.0082), (RT + 0.0125, 0.0082),
             (RT + 0.0145, 0.0068), (RT + 0.015, 0.0001)], cx=0.0, cy=-0.215, segs=24, axis="y")
    for k in range(3):
        g.lathe([(RT + 0.0068 + 0.002 * k, 0.0086), (RT + 0.0078 + 0.002 * k, 0.0086)], cx=0.0, cy=-0.215,
                segs=24, axis="y")
    g.done("cocking_knob", "steel", bevel=0.0004)
    # 机匣前端枪管座 + 两侧螺钉/销
    lathe("barrel_collar", [(RF + 0.002, 0.0145), (RF - 0.008, 0.0145), (RF - 0.009, 0.013)], "steel", segs=28)
    pts = []
    for sx in (-1, 1):
        for z, y in ((-0.016, -0.01), (-0.245, -0.016), (-0.2, -0.026)):
            pts.append((sx * (RX + 0.0003), y, z))
    K.screw_heads("rec_pins", pts, 0.0028, 0.0012)


def lyman_sight():
    """Lyman 可调表尺：底座 + 两侧护耳 + 放倒的游标表尺板（后端带觇孔座）"""
    g = Group()
    g.side([(-0.006, RT - 0.001), (-0.044, RT - 0.001), (-0.044, RT + 0.004, 0.002), (-0.006, RT + 0.005, 0.002)],
           -0.011, 0.011)
    for sx in (-1, 1):
        g.side([(-0.008, RT + 0.002), (-0.03, RT + 0.002), (-0.026, RT + 0.0165, 0.003), (-0.012, RT + 0.0165, 0.003)],
               sx * 0.0112 - 0.0018, sx * 0.0112 + 0.0018)
    g.side([(-0.009, RT + 0.004), (-0.04, RT + 0.004), (-0.04, RT + 0.0075, 0.0015), (-0.009, RT + 0.0085, 0.0015)],
           -0.0065, 0.0065)
    g.side([(-0.009, RT + 0.0045), (-0.016, RT + 0.0045), (-0.016, RT + 0.0125, 0.0015), (-0.009, RT + 0.0125, 0.0015)],
           -0.0048, 0.0048)
    g.cyl((0.0, RT + 0.004, -0.04), 0.0026, 0.024, axis="x", segs=12)
    g.cyl((0.0123, RT + 0.009, -0.018), 0.0032, 0.004, axis="x", segs=14)
    g.done("lyman", "steel", bevel=0.0005)
    cyl("peep", (0.0, RT + 0.0098, -0.0125), 0.0013, 0.008, "bore", axis="z", segs=10, bevel=0.0)


