def grip():
    """SIG 式握把：后背弧、前缘单指凸，两侧横向防滑纹带"""
    def lerp(a, b, t):
        return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    f0, f1 = (-0.0465, LB + 0.0005), (-0.0110, -0.1180)
    r0, r1 = (-0.0040, LB + 0.0005), (0.0255, -0.1070)
    pts = []
    n = 10
    for k in range(n + 1):
        t = k / n
        z, y = lerp(r0, r1, t)
        z += 0.0040 * math.sin(math.pi * t) - 0.0030 * math.exp(-((t - 0.12) / 0.07) ** 2)
        pts.append((z, y, 0.006) if k == n else (z, y))
    for k in range(n + 1):
        t = 1.0 - k / n
        z, y = lerp(f0, f1, t)
        z -= 0.0038 * math.exp(-((t - 0.40) / 0.10) ** 2) - 0.0014 * math.sin(math.pi * t)
        pts.append((z, y, 0.005) if k == 0 else (z, y))
    gp = side("grip", pts, -0.0130, 0.0130, "poly", bevel=0.0035, segs=3)
    taper_x(gp, -0.050, 0.032, 0.80, 1.0)
    c0 = ((f0[0] + r0[0]) * 0.5, (f0[1] + r0[1]) * 0.5)
    c1 = ((f1[0] + r1[0]) * 0.5, (f1[1] + r1[1]) * 0.5)
    L = math.hypot(c1[0] - c0[0], c1[1] - c0[1])
    ax = ((c1[0] - c0[0]) / L, (c1[1] - c0[1]) / L)
    pp = (-ax[1], ax[0]) if -ax[1] > 0 else (ax[1], -ax[0])
    g = Group()
    for sx in (-1, 1):
        for i in range(13):
            s = 0.022 + i * 0.0040
            a = (c0[0] + ax[0] * s, c0[1] + ax[1] * s)
            p0 = (a[0] - pp[0] * 0.0080, a[1] - pp[1] * 0.0080)
            p1 = (a[0] + pp[0] * 0.0110, a[1] + pp[1] * 0.0110)
            h = 0.0011
            poly = [(p0[0] + ax[0] * h, p0[1] + ax[1] * h), (p1[0] + ax[0] * h, p1[1] + ax[1] * h),
                    (p1[0] - ax[0] * h, p1[1] - ax[1] * h), (p0[0] - ax[0] * h, p0[1] - ax[1] * h)]
            zc = a[0]
            xx = 0.0130 * (0.80 + 0.20 * min(1.0, max(0.0, (zc + 0.050) / 0.082)))
            g.side(poly, sx * (xx - 0.0003), sx * (xx + 0.0006))
    g.done("grip_ribs", "poly", bevel=0.0)


