def magazine():
    """30 发 9mm 直弹匣（聚合物）：上窄下略宽，底部两侧横纹 + 带前唇底板"""
    w0, w1 = 0.0108, 0.0114
    zr = MR - 0.0050
    top_y, bot_y = -0.0300, -0.1780
    zf_top, zf_bot = MF + 0.0055, MF + 0.0028
    m = side("magazine", [(zr, top_y), (zr + 0.0010, bot_y), (zf_bot, bot_y), (zf_top, top_y)], -w1, w1, "poly",
             bevel=0.0014, segs=2)
    deform(m, lambda x, y, z: (x * (w0 + (w1 - w0) * min(1.0, max(0.0, (top_y - y) / (top_y - bot_y)))) / w1, y, z))
    g = Group()
    for sx in (-1, 1):
        for k in range(6):
            y = bot_y + 0.0120 + k * 0.0055
            g.side([(zr - 0.0060, y - 0.0012), (zf_bot + 0.0060, y - 0.0012), (zf_bot + 0.0060, y + 0.0012),
                    (zr - 0.0060, y + 0.0012)], sx * (w1 - 0.0004), sx * (w1 + 0.0006))
    g.done("mag_ribs", "poly", bevel=0.0)
    side("mag_floor", [(zr + 0.0022, bot_y + 0.0035), (zf_bot - 0.0040, bot_y + 0.0035), (zf_bot - 0.0045, bot_y - 0.0010, 0.002),
                       (zf_bot - 0.0020, bot_y - 0.0050, 0.002), (zr + 0.0020, bot_y - 0.0050, 0.002)],
         -w1 - 0.0012, w1 + 0.0012, "poly", bevel=0.0012)


