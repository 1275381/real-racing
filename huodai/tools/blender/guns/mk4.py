# ---------------- 小工具（同 m4a1） ----------------

def _rot_new(bm, n0, deg, cx=0.0, cy=0.0):
    bm.verts.ensure_lookup_table()
    bmesh.ops.rotate(bm, cent=K.B(cx, cy, 0.0), matrix=Matrix.Rotation(math.radians(-deg), 3, "Y"),
                     verts=bm.verts[n0:])


def _tube(bm, outer, inner, z0, z1):
    n = len(outer)

    def ring(pts, z):
        return [bm.verts.new(K.B(p[0], p[1], z)) for p in pts]
    o0, o1, i0, i1 = ring(outer, z0), ring(outer, z1), ring(inner, z0), ring(inner, z1)
    for j in range(n):
        j2 = (j + 1) % n
        bm.faces.new((o0[j], o0[j2], o1[j2], o1[j]))
        bm.faces.new((i0[j2], i0[j], i1[j], i1[j2]))
        bm.faces.new((o0[j2], o0[j], i0[j], i0[j2]))
        bm.faces.new((o1[j], o1[j2], i1[j2], i1[j]))


def _slot(bm, zc, length, width, dist, deg, depth=0.008, cy=0.0):
    n0 = len(bm.verts)
    h = width * 0.5
    K.side_bm(bm, [(zc - length * 0.5, cy - h, h * 0.98), (zc + length * 0.5, cy - h, h * 0.98),
                   (zc + length * 0.5, cy + h, h * 0.98), (zc - length * 0.5, cy + h, h * 0.98)],
              dist - depth, dist + depth)
    _rot_new(bm, n0, deg, 0.0, cy)


def _lowpoly():
    for o in K.PARTS:
        md = o.modifiers.get("bev")
        if md and md.width <= 0.00065:
            md.segments = 1


