"""AKM（7.62×39，冲压机匣 + 层压木枪托护木 + 胶木弧形弹匣）。

真实尺寸建模（米）：原点 z=0 = 机匣后端面，y=0 = 枪膛轴线；全长约 0.887 m
（枪口制退器前缘 z=-0.625 → 枪托底板 z=+0.262）。
"""
import math

import gun_kit as K
from gun_kit import Group, side, xsec, lathe, box, cyl, cut, cutter_box, taper_x, deform

# 真枪握把顶后缘（虎口位）→ 程序化 AKM grip_hold；整枪缩到程序化长度
META = dict(ref=(0.0, -0.042, 0.0), target=(0.0, -0.0165, 0.099), length=1.0759)

RX = 0.0175          # 机匣半宽
RB = -0.047          # 机匣下沿
RT = 0.012           # 机匣侧板上沿（防尘盖压在上面）


def receiver():
    rec = side("receiver", [(0.0, RT), (0.0, -0.040, 0.004), (-0.004, RB), (-0.245, RB),
                            (-0.245, RT)], -RX, RX, "steel", bevel=0.0012)
    # 右侧抛壳窗（露出机框）、两侧弹匣井上方冲压凹点
    cut(rec, cutter_box("ejport", (RX, 0.0055, -0.112), (0.006, 0.0125, 0.092), r=0.002))
    for sx in (-1, 1):
        cut(rec, cutter_box("dimple%d" % sx, (sx * RX, -0.022, -0.148), (0.0016, 0.009, 0.026), r=0.002))
    # 机框（抛壳窗里露出的亮钢）+ 拉机柄
    box("carrier", (0.009, 0.006, -0.118), (0.016, 0.0125, 0.11), "steel", bevel=0.0008)
    g = Group()
    g.cyl((0.027, 0.0075, -0.168), 0.0035, 0.024, axis="x", segs=14)
    g.lathe([(0.036, 0.0001), (0.0365, 0.0055), (0.044, 0.0068), (0.048, 0.0055), (0.0486, 0.0001)],
            cx=0.0075, cy=-0.168, segs=16, axis="x")
    g.done("charging_handle", "steel", bevel=0.0004)
    # 防尘盖：拱形截面 + 横向冲压加强筋 + 后端复进簧导杆按钮
    pts = [(RX + 0.0004, RT - 0.001)] + \
        [(RX * 1.03 * math.cos(math.radians(a)), RT + 0.0185 * math.sin(math.radians(a))) for a in range(5, 176, 10)] + \
        [(-RX - 0.0004, RT - 0.001)]
    xsec("dust_cover", pts, -0.203, 0.004, "steel", bevel=0.0008)
    ribs = Group()
    for zc in (-0.17, -0.12, -0.07, -0.025):
        rp = [(RX * 0.98 * math.cos(math.radians(a)), RT + 0.0192 * math.sin(math.radians(a))) for a in range(20, 161, 10)]
        rp = rp + [(x * 0.9, RT + (y - RT) * 0.9 - 0.0006) for x, y in rp[::-1]]
        ribs.xsec(rp, zc - 0.004, zc + 0.004)
    ribs.lathe([(0.004, 0.0042), (0.0095, 0.0042), (0.0105, 0.0032), (0.0106, 0.0001)], cx=0.0, cy=0.017, segs=16)
    ribs.done("cover_ribs", "steel", bevel=0.0005)
    # 铆钉（前后机匣连接座、扳机组销轴）
    g = Group()
    for sx in (-1, 1):
        x = sx * (RX + 0.0004)
        for z, y in ((-0.012, -0.008), (-0.012, -0.031), (-0.205, -0.014), (-0.226, -0.011),
                     (-0.215, -0.034), (-0.052, -0.029), (-0.083, -0.029), (-0.032, -0.02)):
            g.cyl((x, y, z), 0.0026 if z > -0.1 else 0.003, 0.0016, axis="x", segs=12)
    g.done("rivets", "steel", bevel=0.0004)


