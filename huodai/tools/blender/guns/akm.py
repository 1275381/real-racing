def handguards():
    # 下护木：U 形截面，前端收窄，两侧两道指槽
    lw = [(-0.0195, -0.001), (0.0195, -0.001), (0.0205, -0.024, 0.008), (0.012, -0.041, 0.008),
          (-0.012, -0.041, 0.008), (-0.0205, -0.024, 0.008)]
    lo = xsec("lower_hg", lw, -0.252, -0.445, "wood_red", bevel=0.0025, segs=3)

    def lo_shape(x, y, z):
        t = min(1.0, max(0.0, (-0.252 - z) / 0.193))
        s = 1.0 - 0.13 * t
        if y < -0.002:
            y = -0.002 + (y + 0.002) * (1.0 - 0.18 * t)
        # 后端下缘圆收
        return (x * s, y, z)
    deform(lo, lo_shape)
    for sx in (-1, 1):
        for yy in (-0.016, -0.027):
            cut(lo, cutter_box("groove%d%s" % (sx, yy), (sx * 0.021, yy, -0.352), (0.004, 0.0042, 0.13), r=0.002))
    # 上护木（盖住导气管）
    upp = [(0.0158, 0.011)] + [(0.0155 * math.cos(math.radians(a)), 0.0255 + 0.0158 * math.sin(math.radians(a)))
                               for a in range(-15, 196, 15)] + [(-0.0158, 0.011)]
    uh = xsec("upper_hg", upp, -0.306, -0.47, "wood_red", bevel=0.0022, segs=3)
    taper_x(uh, -0.306, -0.47, 1.0, 0.92)
    # 护木前后钢箍 + 前箍右侧锁杆
    g = Group()
    band = [(-0.0215, 0.0), (0.0215, 0.0), (0.0222, -0.024, 0.008), (0.0125, -0.0425, 0.008),
            (-0.0125, -0.0425, 0.008), (-0.0222, -0.024, 0.008)]
    g.xsec([(p[0] * 0.9, p[1]) + tuple(p[2:]) for p in band], -0.445, -0.457)
    g.xsec(band, -0.245, -0.254)
    g.done("hg_bands", "steel", bevel=0.0007)
    side("hg_lever", [(-0.447, -0.004), (-0.455, -0.004), (-0.47, -0.012, 0.002), (-0.466, -0.017, 0.002)],
         0.0195, 0.0213, "steel", bevel=0.0004)


def magazine():
    """30 发胶木弧形弹匣：前后沿二次曲线外弯，底板钢包边，两侧加强筋"""
    n = 14
    back = [(-0.118 - 0.09 * (k / n) ** 1.55, RB + 0.004 - 0.2 * (k / n)) for k in range(n + 1)]
    front = [(-0.181 - 0.097 * (k / n) ** 1.45, RB + 0.004 - 0.186 * (k / n)) for k in range(n + 1)]
    pts = back + front[::-1]
    m = side("magazine", pts, -0.0158, 0.0158, "bakelite", bevel=0.0018, segs=3)
    # 前沿挂钩
    box("mag_lug", (0.0, RB + 0.002, -0.184), (0.014, 0.006, 0.008), "bakelite", bevel=0.0008)
    # 两侧弧形加强筋
    g = Group()
    for sx in (-1, 1):
        rib = []
        for k in range(n + 1):
            t = k / n
            zb = -0.118 - 0.09 * t ** 1.55
            zf = -0.181 - 0.097 * t ** 1.45
            y = RB + 0.004 - 0.193 * t
            rib.append(((zb + zf) * 0.5 + 0.004, y))
        poly = [(z + 0.003, y) for z, y in rib] + [(z - 0.003, y) for z, y in rib[::-1]]
        g.side(poly[1:-1], sx * 0.0158 - 0.0004, sx * 0.0158 + sx * 0.0012)
    g.done("mag_ribs", "bakelite", bevel=0.0006)
    # 底板
    zb, yb = back[-1]
    zf, yf = front[-1]
    side("mag_floor", [(zb + 0.003, yb + 0.004), (zf - 0.004, yf + 0.004), (zf - 0.005, yf - 0.0025, 0.002),
                       (zb + 0.004, yb - 0.0035, 0.002)], -0.0172, 0.0172, "steel", bevel=0.0008)
    return m


def build():
    receiver()
    controls()
    grip()
    stock()
    barrel_group()
    rear_sight()
    handguards()
    magazine()
