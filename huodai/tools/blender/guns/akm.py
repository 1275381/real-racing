def barrel_group():
    # 枪管（不同段外径）+ 前端螺纹
    lathe("barrel", [(-0.245, 0.0105), (-0.33, 0.0098), (-0.45, 0.0088), (-0.53, 0.0084), (-0.595, 0.0078),
                     (-0.6, 0.0072), (-0.606, 0.0072)], "steel", segs=28)
    # 斜切制退器（右前角斜削）+ 枪口内膛
    br = lathe("muzzle_brake", [(-0.6, 0.0105), (-0.624, 0.0108), (-0.625, 0.0098), (-0.625, 0.0001)], "steel", segs=28)
    bm_cut = K.Group()
    K.top_bm(bm_cut.bm, [(0.0, -0.634), (0.03, -0.634), (0.03, -0.606)], -0.03, 0.03)
    cut(br, K.obj("brake_cut", bm_cut.bm, None, cutter=True))
    cyl("bore", (0.0, 0.0, -0.6232), 0.0042, 0.004, "bore", axis="z", segs=20, bevel=0.0)
    # 导气箍 + 导气管前端 + 刺刀座
    g = Group()
    g.lathe([(-0.528, 0.0135), (-0.556, 0.0135)], segs=28)
    g.box((0.0, 0.012, -0.542), (0.019, 0.024, 0.026))
