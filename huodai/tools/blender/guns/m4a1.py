def grip():
    """A2 握把：前缘手指凸、后背弧、底面垂直握把轴；两侧菱形防滑格"""
    def lerp(a, b, t):
        return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    f0, f1 = (-0.0272, LB + 0.0005), (0.0110, -0.1235)
    r0, r1 = (0.0125, LB + 0.0005), (0.0435, -0.1110)
    pts = []
    n = 10
    for k in range(n + 1):               # 后背：顶端尾舌，下面收进（虎口），中段鼓
        t = k / n
        z, y = lerp(r0, r1, t)
        z += 0.0032 * math.sin(math.pi * t) - 0.0030 * math.exp(-((t - 0.12) / 0.07) ** 2)
        pts.append((z, y, 0.006) if k == n else (z, y))
    for k in range(n + 1):               # 前缘：手指凸
        t = 1.0 - k / n
        z, y = lerp(f0, f1, t)
        z -= 0.0046 * math.exp(-((t - 0.43) / 0.09) ** 2) - 0.0016 * math.sin(math.pi * t)
        pts.append((z, y, 0.005) if k == 0 else (z, y))
    gp = side("grip", pts, -0.0132, 0.0132, "poly", bevel=0.0035, segs=3)
    taper_x(gp, -0.032, 0.048, 0.80, 1.0)
    # 两侧菱形防滑格（沿握把轴斜排）
    c0 = ((f0[0] + r0[0]) * 0.5, (f0[1] + r0[1]) * 0.5)
    c1 = ((f1[0] + r1[0]) * 0.5, (f1[1] + r1[1]) * 0.5)
    L = math.hypot(c1[0] - c0[0], c1[1] - c0[1])
    ax = ((c1[0] - c0[0]) / L, (c1[1] - c0[1]) / L)
    pp = (-ax[1], ax[0]) if -ax[1] > 0 else (ax[1], -ax[0])      # 垂直握把轴、朝后
    g = Group()
    d = 0.0016
    for sx in (-1, 1):
        for i in range(11):
            for j in range(-3, 3):
                s = 0.024 + i * 0.0042 + (0.0021 if j % 2 else 0.0)
                c = j * 0.0036 + 0.0030
                zc = c0[0] + ax[0] * s + pp[0] * c
                yc = c0[1] + ax[1] * s + pp[1] * c
                xx = 0.0132 * (0.80 + 0.20 * min(1.0, max(0.0, (zc + 0.032) / 0.080)))
                g.side([(zc, yc + d), (zc + d, yc), (zc, yc - d), (zc - d, yc)],
                       sx * (xx - 0.0003), sx * (xx + 0.0006))
    g.done("grip_checker", "poly", bevel=0.0)


