def magazine():
    """30 发铝制 STANAG 弹匣：上段直、下段微前弯，底板垂直于匣身；两侧冲压筋"""
    d, w = 0.0605, 0.0111
    zr0, yc0 = MR - 0.0045, -0.0300       # 后沿 z、直段起点（井内）
    ystr = -0.0800                        # 直段终点（弯段开始）
    R, alpha = 0.38, math.radians(16.5)
    zc0 = zr0 - d * 0.5
    ls = yc0 - ystr

    def center(s):
        """s：沿匣身向下的弧长 → 中心线点 + 朝后的法向"""
        if s <= ls:
            return (zc0, yc0 - s), (1.0, 0.0)
        phi = (s - ls) / R
        return (zc0 - R * (1 - math.cos(phi)), ystr - R * math.sin(phi)), (math.cos(phi), -math.sin(phi))
    total = ls + R * alpha
    n = 16
    rear, front, mid = [], [], []
    for k in range(n + 1):
        s = ls * k / 4 if k <= 4 else ls + R * alpha * (k - 4) / (n - 4)
        (cz, cy), (nz, ny) = center(s)
        rear.append((cz + nz * d * 0.5, cy + ny * d * 0.5))
        front.append((cz - nz * d * 0.5, cy - ny * d * 0.5))
        mid.append(((cz, cy), (nz, ny)))
    side("magazine", rear + front[::-1], -w, w, "alu", bevel=0.0012, segs=2)
    # 两侧冲压加强筋（沿匣身）
    g = Group()
    for sx in (-1, 1):
        for off in (0.0150, -0.0040):
            strip = [(cz + nz * off, cy + ny * off) for (cz, cy), (nz, ny) in mid[3:-1]]
            poly = [(z + 0.0028, y) for z, y in strip] + [(z - 0.0028, y) for z, y in strip[::-1]]
            g.side(poly, sx * (w - 0.0004), sx * (w + 0.0007))
    g.done("mag_ribs", "alu", bevel=0.0005)
    # 底板（钢，前伸挂唇）：a 沿后法向，b 沿匣身向下
    (cz, cy), (nz, ny) = mid[-1]
    dz, dy = -math.sin(alpha), -math.cos(alpha)

    def P(a, b):
        return (cz + nz * a + dz * b, cy + ny * a + dy * b)
    side("mag_floor", [P(d * 0.5 + 0.0018, -0.0040), P(-d * 0.5 - 0.0045, -0.0040), P(-d * 0.5 - 0.0045, 0.0018),
                       P(-d * 0.5 - 0.0020, 0.0042), P(d * 0.5 + 0.0018, 0.0042)],
         -w - 0.0010, w + 0.0010, "steel", bevel=0.0007)


