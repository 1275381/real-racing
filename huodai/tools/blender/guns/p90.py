"""FN P90 TR（5.7×28，无托聚合物枪身 + 顶置 50 发横置弹匣 + 三面皮卡汀尼导轨）。

真实尺寸建模（米）：原点 z=0 = 橡胶托底板后端面，y=0 = 枪膛轴线；全长 0.500 m
（消焰器前缘 z=-0.500）。双色：枪身 OD 绿聚合物，弹匣 / 导轨座 / 小件黑色。
拇指孔握把（后孔）+ 扳机护圈（前孔）一体成型，前下方护手挡；
两侧对称拉机柄在前端，旋钮式快慢机在扳机正下方。
"""
import math

import gun_kit as K
from gun_kit import Group, side, xsec, lathe, box, cyl, cut, cutter_box, taper_x, deform, picatinny

# 握把顶后缘（拇指孔前上角，虎口位）→ 程序化 P90 grip；整枪缩到程序化长度
META = dict(ref=(0.0, -0.036, -0.25), target=(0.0, -0.0494, 0.0446), length=0.5164)

HW = 0.0275          # 上机匣半宽（全宽 55 mm）
YB = -0.034          # 上机匣下沿
MAG_B, MAG_T = 0.0225, 0.0515   # 弹匣上下沿
RAIL_Y = 0.062       # 顶导轨座面


def dens(pts, step=0.005, segs=4):
    """先圆角再按步长加密轮廓点（之后做非线性变形时侧面不会被长边拉直）"""
    p2 = K.rounded(pts, 0.0, segs)
    out = []
    n = len(p2)
    for i in range(n):
        a, b = p2[i], p2[(i + 1) % n]
        d = math.hypot(b[0] - a[0], b[1] - a[1])
        k = max(1, int(d / step))
        for j in range(k):
            t = j / k
            out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return out


def smooth(t):
    t = min(1.0, max(0.0, t))
    return t * t * (3 - 2 * t)


def frame_hw(z):
    """握把框半宽：托底宽 → 拇指孔/握把/护圈窄 → 前护手再放宽"""
    w = 0.0262 + (0.0186 - 0.0262) * smooth((-0.085 - z) / 0.1)
    return w + (0.0228 - 0.0186) * smooth((-0.365 - z) / 0.05)


def upper():
    # 机匣：圆角截面挤出（两侧微鼓），弹匣平躺在顶面弹匣槽里
    xs = [(-0.0252, YB, 0.012), (0.0252, YB, 0.012), (HW, -0.016), (HW + 0.0006, 0.004), (HW, 0.022),
          (0.0262, 0.030, 0.0025), (-0.0262, 0.030, 0.0025), (-HW, 0.022), (-HW - 0.0006, 0.004), (-HW, -0.016)]
    rec = xsec("receiver", xs, -0.009, -0.399, "poly", r=0.0, bevel=0.004, segs=4)
    # 抛壳口（拇指孔顶部，向下抛壳）
    cut(rec, cutter_box("ejchute", (0.0, YB, -0.19), (0.016, 0.012, 0.034), r=0.003))
    box("chute_dark", (0.0, YB + 0.005, -0.19), (0.015, 0.004, 0.032), "bore", bevel=0.0)
    # 托腮鼓包（弹匣后方，上沿与弹匣顶齐平）
    side("cheek", [(-0.009, 0.024), (-0.009, 0.041, 0.01), (-0.024, 0.0505, 0.01), (-0.057, 0.0505, 0.004),
                   (-0.066, 0.040, 0.005), (-0.075, 0.028, 0.003), (-0.075, 0.024)],
         -HW + 0.0004, HW - 0.0004, "poly", bevel=0.005, segs=4)
    # 枪管组（前段）：圆鼻 + 拉机柄滑槽
    nose = side("nose", [(-0.397, YB + 0.001), (-0.397, 0.030), (-0.468, 0.030, 0.008), (-0.4745, 0.012, 0.01),
                         (-0.4745, -0.014, 0.01), (-0.469, YB + 0.001, 0.008)],
                -HW, HW, "poly", bevel=0.0055, segs=4)
    taper_x(nose, -0.40, -0.474, 1.0, 0.9)
    for sx in (-1, 1):
        cut(nose, cutter_box("chslot%d" % sx, (sx * HW, 0.011, -0.426), (0.008, 0.0048, 0.068), r=0.0022))
    # 拉机柄（两侧对称，在滑槽前端）
    g = Group()
    for sx in (-1, 1):
        g.cyl((sx * (HW - 0.001), 0.011, -0.452), 0.0022, 0.012, axis="x", segs=12)
        g.lathe([(sx * (HW + 0.004), 0.0001), (sx * (HW + 0.004), 0.0048), (sx * (HW + 0.0085), 0.0052),
                 (sx * (HW + 0.0105), 0.0042), (sx * (HW + 0.011), 0.0001)], cx=0.011, cy=-0.452,
                segs=16, axis="x")
    g.done("charging_handles", "poly", bevel=0.0005)
    # 消焰器 + 枪口内膛 + 侧向缝
    lathe("flash_hider", [(-0.466, 0.0095), (-0.4775, 0.0095), (-0.478, 0.0108), (-0.484, 0.0108),
                          (-0.4845, 0.0101), (-0.4875, 0.0101), (-0.488, 0.0108), (-0.4985, 0.0108),
                          (-0.5, 0.0098), (-0.5, 0.0062), (-0.494, 0.0055)], "steel", segs=28)
    cyl("bore", (0.0, 0.0, -0.4945), 0.0058, 0.002, "bore", axis="z", segs=20, bevel=0.0)
    g = Group()
    for k in range(6):
        a = math.radians(30 + 60 * k)
        g.box((0.0109 * math.cos(a), 0.0109 * math.sin(a), -0.4925), (0.0022, 0.0022, 0.0085))
    g.done("hider_slots", "bore", bevel=0.0)


def lower():
    # 握把框：托底 + 拇指孔下梁 + 握把 + 扳机护圈 + 前护手 + 护手挡（一体，宽度沿 z 变化）
    pts = [(-0.009, -0.026), (-0.471, -0.026), (-0.4735, -0.042, 0.006), (-0.47, -0.066, 0.008),
           (-0.459, -0.077, 0.006), (-0.446, -0.0715, 0.006), (-0.43, -0.0555, 0.012),
           (-0.407, -0.0505, 0.016), (-0.388, -0.058, 0.012), (-0.376, -0.088, 0.014),
           (-0.362, -0.1045, 0.012), (-0.3, -0.1125, 0.03), (-0.265, -0.121, 0.012),
           (-0.24, -0.119, 0.014), (-0.2, -0.1095, 0.04), (-0.12, -0.0975, 0.05), (-0.05, -0.0905, 0.03),
           (-0.009, -0.086, 0.006)]
    fr = side("frame", dens(pts), -1.0, 1.0, "poly_od", bevel=0.0058, segs=4)

    def wfn(x, y, z):
        return (x * frame_hw(z), y, z)
    deform(fr, wfn)
    # 拇指孔（大泪滴形）+ 扳机护圈孔
    bm = K.bmesh.new()
    K.side_bm(bm, [(-0.122, -0.018), (-0.2535, -0.018), (-0.254, -0.038, 0.01), (-0.2385, -0.0935, 0.012),
                   (-0.224, -0.0975, 0.012), (-0.17, -0.0845, 0.03), (-0.13, -0.0715, 0.026),
                   (-0.112, -0.046, 0.018)], -0.04, 0.04)
    cut(fr, K.obj("thumbhole", bm, None, cutter=True))
    bm = K.bmesh.new()
    K.side_bm(bm, [(-0.2855, -0.018), (-0.286, -0.04, 0.008), (-0.2685, -0.0945, 0.01), (-0.276, -0.1, 0.008),
                   (-0.338, -0.0975, 0.012), (-0.356, -0.088, 0.01), (-0.3625, -0.052, 0.012),
                   (-0.36, -0.018)], -0.04, 0.04)
    cut(fr, K.obj("tguard", bm, None, cutter=True))
    # 前护手两侧防滑凹纹（护手挡后方，斜纹）
    g = Group()
    for sx in (-1, 1):
        w = frame_hw(-0.43)
        for k in range(5):
            z = -0.437 + 0.0065 * k
            g.side([(z, -0.037), (z - 0.0022, -0.037), (z - 0.0022 + 0.004, -0.051), (z + 0.004, -0.051)],
                   sx * (w - 0.0005), sx * (w + 0.0007))
    g.done("front_grip_ribs", "poly_od", bevel=0.0003)
    # 橡胶托底板
    side("butt_pad", [(0.0, -0.083, 0.006), (0.0, 0.046, 0.008), (-0.0115, 0.048, 0.003), (-0.0115, -0.087, 0.004)],
         -0.0262, 0.0262, "rubber", bevel=0.0035, segs=3)


def controls():
    # 扳机（护圈前孔后上角下垂的弧形扳机板）
    side("trigger", [(-0.29, -0.028), (-0.3, -0.028), (-0.303, -0.05, 0.006), (-0.297, -0.066, 0.004),
                     (-0.291, -0.068), (-0.293, -0.06, 0.004), (-0.294, -0.046)], -0.004, 0.004, "poly", bevel=0.0007)
    # 旋钮快慢机（扳机正下方，护圈底梁上）
    g = Group()
    g.cyl((0.0, -0.0975, -0.298), 0.0098, 0.004, axis="y", segs=24)
    g.box((0.0, -0.0945, -0.298), (0.003, 0.003, 0.018))
    g.done("selector", "poly", bevel=0.0006)
    # 弹匣卡笋（弹匣后端两侧拨片）
    g = Group()
    for sx in (-1, 1):
        g.side([(-0.056, 0.049), (-0.068, 0.049), (-0.067, 0.0555, 0.0015), (-0.058, 0.0555, 0.0015)],
               sx * 0.009, sx * 0.022)
    g.done("mag_release", "poly", bevel=0.0006)
    # 背带扣座：前（护手挡两侧）+ 后（托底两侧）钢杯 + 暗孔
    g = Group()
    d = Group()
    for sx in (-1, 1):
        for z, y in ((-0.452, -0.044), (-0.03, -0.066)):
            w = frame_hw(z)
            g.cyl((sx * (w + 0.0006), y, z), 0.0058, 0.0024, axis="x", segs=20)
            d.cyl((sx * (w + 0.0019), y, z), 0.0033, 0.0004, axis="x", segs=16)
    g.done("sling_cups", "steel", bevel=0.0004)
    d.done("sling_holes", "bore", bevel=0.0)
    # 机匣两侧销钉
    pts = []
    for sx in (-1, 1):
        for z, y in ((-0.11, -0.016), (-0.33, -0.018), (-0.432, -0.017)):
            pts.append((sx * (HW + 0.0003), y, z))
    K.screw_heads("pins", pts, 0.0028, 0.0012, zone="poly")


def magazine():
    """50 发横置弹匣：平躺在机匣顶部弹匣槽里，前端塞进导轨座下"""
    mg = side("magazine", [(-0.068, MAG_B, 0.003), (-0.068, MAG_T - 0.003, 0.004), (-0.077, MAG_T, 0.004),
                           (-0.402, MAG_T), (-0.402, MAG_B)], -0.0248, 0.0248, "poly", bevel=0.0018, segs=3)
    # 两侧上下沿凸边（中间透明窗区凹进去的观感）+ 后端防滑横纹 + 顶面纵筋
    g = Group()
    for sx in (-1, 1):
        for y0, y1 in ((MAG_T - 0.005, MAG_T - 0.0018), (MAG_B + 0.0075, MAG_B + 0.0105)):
            g.side([(-0.08, y0), (-0.402, y0), (-0.402, y1), (-0.08, y1)], sx * 0.0246, sx * 0.0257)
        g.side([(-0.072, MAG_B + 0.006), (-0.08, MAG_B + 0.006), (-0.08, MAG_T - 0.002), (-0.072, MAG_T - 0.002)],
               sx * 0.0246, sx * 0.0256)
    for k in range(5):
        z = -0.082 - 0.006 * k
        g.box((0.0, MAG_T + 0.0006, z), (0.04, 0.0016, 0.0026))
    for sx in (-1, 1):
        g.box((sx * 0.016, MAG_T + 0.0005, -0.24), (0.003, 0.0014, 0.25))
    g.done("mag_ribs", "poly", bevel=0.0004)
    return mg


def rails():
    # 前导轨座（弹匣前端插在其下）
    side("rail_base", [(-0.394, 0.0255), (-0.394, RAIL_Y), (-0.469, RAIL_Y, 0.006), (-0.4735, 0.044, 0.006),
                       (-0.469, 0.0255)], -0.026, 0.026, "poly", bevel=0.003, segs=3)
    # 导轨护罩：顶板 + 两侧裙边罩住弹匣上沿，后端斜收
    sh = [(-HW, 0.041, 0.0015), (-HW, RAIL_Y, 0.003), (HW, RAIL_Y, 0.003), (HW, 0.041, 0.0015),
          (0.0252, 0.041), (0.0252, MAG_T + 0.002), (-0.0252, MAG_T + 0.002), (-0.0252, 0.041)]
    hood = xsec("rail_hood", sh, -0.25, -0.396, "poly", bevel=0.0012)
    bm = K.bmesh.new()
    K.side_bm(bm, [(-0.245, 0.03), (-0.245, 0.07), (-0.275, 0.07)], -0.04, 0.04)
    cut(hood, K.obj("hood_rear", bm, None, cutter=True))
    picatinny("rail_top", -0.466, -0.262, RAIL_Y, zone="alu")
    # 两侧短导轨（导轨座前端左右）
    for sx in (-1, 1):
        r = picatinny("rail_side%d" % sx, -0.463, -0.405, 0.0, zone="alu")

        def rot(x, y, z, sx=sx):
            return (sx * (0.026 + y), 0.0435 - sx * x, z)
        deform(r, rot)


def build():
    upper()
    lower()
    controls()
    magazine()
    rails()
