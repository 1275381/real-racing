"""KRISS Vector Gen II SMG（9×19，5.5" 枪管 + 短护管 + 螺纹枪口小消焰器，M4 侧折托座 + M4 伸缩托展开）。

真实尺寸建模（米）：原点 z=0 = 机匣后端面（侧折托座接口），y=0 = 枪膛轴线；
全长约 0.657 m（消焰器前缘 z=-0.400 → 托底板 z=+0.257）。
枪管轴线低（与握持手对齐）、顶导轨高；握把前的下机匣是向前上方斜收的
"Super V" 斜块壳体，Glock 17 弹匣插在其后下方（扳机护圈正前）。
铝上机匣（整条皮卡汀尼 + 折叠前后表尺，右抛壳窗、左前拉机柄），聚合物下机匣。
"""
import math

import gun_kit as K
from gun_kit import Group, side, xsec, lathe, box, cyl, cut, cutter_box, taper_x, deform, picatinny

# 游戏约束：顶导轨面要在 y≈0.09（红点镜固定在旧锚点上）。按真枪比例虎口在 y=-0.028，
# 这里 ref 取在握把后缘再往下 1.3 cm 处（y=-0.0407），让导轨面落到 0.09；
# 若改用真虎口 ref=(0, -0.028, -0.044)，导轨面会落在 game y≈0.076（比要求低 1.4 cm）。
META = dict(ref=(0.0, -0.0407, -0.0425), target=(0.0, -0.0199, 0.0017), length=0.7295)

UHW = 0.0165         # 上机匣半宽
LHW = 0.0235         # 下机匣半宽
RAIL_Y = 0.0514      # 导轨座面（齿顶 +6.6 mm）
UB = 0.010           # 上机匣下沿（与下机匣搭接）


def upper():
    # 上机匣截面：两侧直壁 + 上肩斜切到导轨座
    xs = [(-UHW, UB), (UHW, UB), (UHW, 0.039), (0.0118, RAIL_Y - 0.0022), (0.0118, RAIL_Y),
          (-0.0118, RAIL_Y), (-0.0118, RAIL_Y - 0.0022), (-UHW, 0.039)]
    up = xsec("upper", xs, 0.0, -0.331, "alu", bevel=0.0009)
    # 前端上斜面
    bm = K.bmesh.new()
    K.side_bm(bm, [(-0.322, 0.06), (-0.34, 0.06), (-0.34, 0.03)], -0.03, 0.03)
    cut(up, K.obj("upper_nose", bm, None, cutter=True))
    # 右侧抛壳窗（露出枪机）+ 左前拉机柄滑槽
    cut(up, cutter_box("ejport", (UHW, 0.026, -0.138), (0.008, 0.017, 0.056), r=0.002))
    cut(up, cutter_box("chslot", (-UHW, 0.031, -0.245), (0.006, 0.0055, 0.09), r=0.0022))
    box("bolt", (0.008, 0.026, -0.138), (0.014, 0.017, 0.056), "steel", bevel=0.0008)
    box("bolt_face", (UHW - 0.0035, 0.0235, -0.15), (0.0014, 0.006, 0.02), "bore", bevel=0.0)
    # 拉机柄（左侧折叠柄，在滑槽前端）
    g = Group()
    g.box((-UHW - 0.004, 0.031, -0.285), (0.008, 0.005, 0.009))
    g.side([(-0.279, 0.026), (-0.291, 0.026), (-0.293, 0.036, 0.003), (-0.281, 0.0375, 0.003)],
           -UHW - 0.019, -UHW - 0.007)
    g.done("charging_handle", "steel", bevel=0.0006)
    picatinny("rail", -0.33, -0.002, RAIL_Y, zone="alu")
    # 折叠表尺：后（导轨尾）+ 前（导轨头）——底座夹块 + 放倒的表尺片
    g = Group()
    ry = RAIL_Y + 0.0066
    g.side([(-0.004, RAIL_Y + 0.002), (-0.036, RAIL_Y + 0.002), (-0.036, ry + 0.004, 0.002),
            (-0.004, ry + 0.007, 0.002)], -0.0115, 0.0115)
    g.side([(-0.009, ry + 0.006), (-0.034, ry + 0.0035), (-0.034, ry + 0.0075, 0.002), (-0.012, ry + 0.0105, 0.002)],
           -0.009, 0.009)
    g.side([(-0.298, RAIL_Y + 0.002), (-0.329, RAIL_Y + 0.002), (-0.329, ry + 0.007, 0.002),
            (-0.298, ry + 0.004, 0.002)], -0.0115, 0.0115)
    g.side([(-0.301, ry + 0.0035), (-0.326, ry + 0.006), (-0.323, ry + 0.0105, 0.002), (-0.301, ry + 0.0075, 0.002)],
           -0.0075, 0.0075)
    for sx in (-1, 1):
        g.cyl((sx * 0.0122, ry + 0.003, -0.012), 0.0032, 0.004, axis="x", segs=14)
        g.cyl((sx * 0.0122, ry + 0.003, -0.322), 0.0032, 0.004, axis="x", segs=14)
    g.done("flip_sights", "alu", bevel=0.0006)


def lower():
    # 下机匣：尾段 + 扳机护圈上方 + 弹匣井 + Super V 斜块 + 前护管（底导轨）
    pts = [(0.0, 0.016), (0.0, -0.02, 0.006), (-0.012, -0.03, 0.006), (-0.1245, -0.03),
           (-0.113, -0.106, 0.005), (-0.116, -0.11, 0.003), (-0.18, -0.11, 0.007),
           (-0.268, -0.0245, 0.012), (-0.332, -0.0245, 0.004), (-0.339, -0.017, 0.006),
           (-0.339, 0.012, 0.005), (-0.332, 0.016)]
    lo = side("lower", pts, -LHW, LHW, "poly", bevel=0.003, segs=3)
    # 斜块侧面三角凹面（Super V 壳体特征，斜边平行于前下斜面）
    for sx in (-1, 1):
        bm = K.bmesh.new()
        K.side_bm(bm, [(-0.147, -0.094, 0.006), (-0.17, -0.094, 0.006), (-0.247, -0.031, 0.006),
                       (-0.147, -0.031, 0.006)], sx * (LHW - 0.0025), sx * (LHW + 0.004))
        cut(lo, K.obj("vpanel%d" % sx, bm, None, cutter=True))
    # 弹匣井口外扩唇
    side("well_lip", [(-0.109, -0.097), (-0.109, -0.106, 0.003), (-0.114, -0.1125, 0.003), (-0.181, -0.1125, 0.004),
                      (-0.175, -0.097)], -LHW - 0.0012, LHW + 0.0012, "poly", bevel=0.0015, segs=2)
    # 扳机护圈（握把前缘 → 弹匣井后沿）
    side("trigger_guard", [(-0.066, -0.028), (-0.064, -0.064, 0.006), (-0.07, -0.075, 0.008),
                           (-0.12, -0.075, 0.006), (-0.124, -0.068), (-0.124, -0.028), (-0.118, -0.028),
                           (-0.118, -0.067, 0.004), (-0.114, -0.069, 0.003), (-0.074, -0.069, 0.006),
                           (-0.0705, -0.062, 0.004), (-0.072, -0.028)],
         -0.0085, 0.0085, "poly", bevel=0.0018, segs=3)
    # 前护管底导轨（朝下）
    r = picatinny("rail_bottom", -0.33, -0.272, 0.0, zone="alu")
    deform(r, lambda x, y, z: (-x, -0.0245 - y + 0.001, z))
    # 枪管：螺纹段 + A2 鸟笼式消焰器 + 枪口内膛
    lathe("barrel_nut", [(-0.336, 0.0135), (-0.347, 0.0135), (-0.348, 0.0115)], "alu", segs=24)
    lathe("barrel", [(-0.33, 0.0085), (-0.346, 0.0085), (-0.347, 0.0072), (-0.358, 0.0072)], "steel", segs=24)
    fh = lathe("flash_hider", [(-0.356, 0.0094), (-0.364, 0.0094), (-0.366, 0.0108), (-0.3985, 0.0108),
                               (-0.4, 0.0101), (-0.4, 0.0062), (-0.394, 0.0058)], "steel", segs=28)
    g = Group()
    for k in range(5):     # 鸟笼开缝：上半圈 5 条，底部不开（防扬尘）
        a = math.radians(10 + 40 * k)
        g.box((0.0109 * math.cos(a), 0.0109 * math.sin(a), -0.385), (0.0024, 0.0024, 0.018))
    g.done("fh_slots", "bore", bevel=0.0)
    cyl("bore", (0.0, 0.0, -0.3955), 0.006, 0.002, "bore", axis="z", segs=20, bevel=0.0)


def grip():
    gp = side("grip", [(-0.042, -0.022), (-0.0435, -0.034, 0.005), (-0.033, -0.07, 0.025), (-0.023, -0.122, 0.01),
                       (-0.029, -0.131, 0.006), (-0.058, -0.131, 0.006), (-0.0635, -0.121, 0.005),
                       (-0.0615, -0.11, 0.005), (-0.067, -0.097, 0.007), (-0.0655, -0.085, 0.005),
                       (-0.0705, -0.071, 0.007), (-0.0715, -0.05, 0.008), (-0.076, -0.022)],
              -0.0145, 0.0145, "poly", r=0.002, bevel=0.0035, segs=3)
    taper_x(gp, -0.075, -0.022, 0.92, 1.0)
    # 握把两侧细横纹防滑区（随握把后倾）
    g = Group()
    for sx in (-1, 1):
        for k in range(14):
            t = k / 13.0
            y = -0.046 - 0.07 * t
            z = -0.052 + 0.016 * t
            g.side([(z + 0.0095, y), (z - 0.0085, y), (z - 0.0085, y - 0.0016), (z + 0.0095, y - 0.0016)],
                   sx * 0.0139, sx * 0.0151)
    g.done("grip_ribs", "poly", bevel=0.0003)


def controls():
    # 扳机
    side("trigger", [(-0.085, -0.028), (-0.093, -0.028), (-0.095, -0.045, 0.004), (-0.09, -0.059, 0.003),
                     (-0.086, -0.06), (-0.088, -0.052, 0.003), (-0.088, -0.04)], -0.0035, 0.0035, "steel",
         bevel=0.0005)
    # 双侧快慢机（握把上方）
    g = Group()
    for sx in (-1, 1):
        g.cyl((sx * (LHW + 0.0008), -0.014, -0.052), 0.0058, 0.0024, axis="x", segs=20)
        g.side([(-0.05, -0.0165), (-0.075, -0.0145, 0.002), (-0.076, -0.0095, 0.002), (-0.052, -0.0115)],
               sx * (LHW + 0.0012), sx * (LHW + 0.0034))
    g.done("selector", "steel", bevel=0.0004)
    # 双侧弹匣卡笋（弹匣井后沿）+ 左侧空仓挂机柄
    g = Group()
    for sx in (-1, 1):
        g.side([(-0.112, -0.034), (-0.12, -0.034), (-0.121, -0.052, 0.002), (-0.113, -0.052, 0.002)],
               sx * (LHW - 0.001), sx * (LHW + 0.002))
    g.side([(-0.135, -0.014), (-0.158, -0.014, 0.002), (-0.158, -0.008, 0.002), (-0.135, -0.008)],
           -LHW - 0.0022, -LHW + 0.001)
    g.done("mag_release", "poly", bevel=0.0005)
    # 下机匣分解销（两侧）
    pts = []
    for sx in (-1, 1):
        for z, y in ((-0.012, -0.008), (-0.1, -0.016), (-0.205, -0.012), (-0.31, -0.008)):
            pts.append((sx * (LHW + 0.0002), y, z))
    K.screw_heads("pins", pts, 0.003, 0.0012, zone="steel")


def magazine():
    """Glock 17 弹匣（17 发）：上窄下略宽，前倾跟握把平行，底板前凸唇"""
    a = math.radians(8.0)
    def P(t, s):   # 沿弹匣轴：t 从井口向下，s 从后沿向前
        return (-0.122 - s * math.cos(a) + t * math.sin(a), -0.035 - t * math.cos(a) - s * math.sin(a) * 0.0)
    L = 0.116
    pts = [P(0, 0.001), P(L, 0.0), P(L, 0.0335), P(0, 0.0325)]
    m = side("magazine", pts, -0.0118, 0.0118, "poly", bevel=0.0018, segs=3)
    taper_x(m, -0.04, -0.15, 0.92, 1.0)
    # 底板（前端上翘唇）
    zb, yb = P(L, 0.0)
    zf, yf = P(L, 0.0335)
    side("mag_floor", [(zb + 0.002, yb + 0.003), (zf - 0.0035, yf + 0.003), (zf - 0.006, yf - 0.002, 0.002),
                       (zf - 0.002, yf - 0.0085, 0.002), (zb + 0.0025, yb - 0.0085, 0.002)],
         -0.0128, 0.0128, "poly", bevel=0.0012, segs=2)
    # 弹匣后沿检视孔（亮钢弹匣里的观察孔：暗色小圆点）
    g = Group()
    for k in range(3):
        z, y = P(0.085 - 0.016 * k, 0.004)
        for sx in (-1, 1):
            g.cyl((sx * 0.0119, y, z), 0.0016, 0.0006, axis="x", segs=10)
    g.done("mag_holes", "bore", bevel=0.0)


def stock():
    # M4 侧折托座（左侧铰链）+ 缓冲管 + 堡垒螺母
    g = Group()
    g.side([(0.0, -0.01), (0.0, 0.038), (0.032, 0.038, 0.004), (0.04, 0.03, 0.004), (0.04, -0.004, 0.004),
            (0.03, -0.01, 0.004)], -0.0155, 0.0155)
    g.cyl((-0.0172, 0.014, 0.032), 0.0045, 0.05, axis="y", segs=16)
    g.done("folder", "alu", bevel=0.0009)
    g = Group()
    d = Group()
    for x, y, z in ((0.0155, 0.012, 0.02), (LHW, -0.012, -0.322), (-LHW, -0.012, -0.322)):
        sx = 1 if x > 0 else -1
        g.cyl((x + sx * 0.0008, y, z), 0.0062, 0.0024, axis="x", segs=20)
        d.cyl((x + sx * 0.0021, y, z), 0.0036, 0.0004, axis="x", segs=16)
    g.done("qd_cups", "steel", bevel=0.0004)
    d.done("qd_holes", "bore", bevel=0.0)
    lathe("tube", [(0.038, 0.0175), (0.046, 0.0175), (0.046, 0.0148), (0.215, 0.0148), (0.218, 0.013),
                   (0.218, 0.0001)], "alu", cy=0.016, segs=28)
    nut = lathe("castle_nut", [(0.046, 0.0195), (0.054, 0.0195)], "steel", cy=0.016, segs=28)
    for k in range(3):
        a = math.radians(30 + 120 * k)
        cut(nut, cutter_box("notch%d" % k, (0.0195 * math.cos(a), 0.016 + 0.0195 * math.sin(a), 0.0505),
                            (0.006, 0.006, 0.006)))
    # M4 伸缩托：主体（套在缓冲管上，下方楔形）+ 侧面凹槽 + 托底橡胶垫 + 锁杆 + 背带环
    st = side("stock", [(0.088, 0.036, 0.004), (0.25, 0.038, 0.004), (0.25, -0.066, 0.004),
                        (0.236, -0.068, 0.006), (0.15, -0.012, 0.03), (0.118, -0.006, 0.008),
                        (0.088, -0.004, 0.004)], -0.018, 0.018, "poly", bevel=0.0025, segs=3)
    taper_x(st, 0.088, 0.25, 0.86, 1.0)
    for sx in (-1, 1):
        bm = K.bmesh.new()
        K.side_bm(bm, [(0.17, 0.026), (0.238, 0.028), (0.238, -0.045), (0.214, -0.048)],
                  sx * 0.0145, sx * 0.022, r=0.003)
        cut(st, K.obj("stock_recess%d" % sx, bm, None, cutter=True))
    side("butt_pad", [(0.249, 0.0395, 0.003), (0.2575, 0.0395, 0.004), (0.2575, -0.0685, 0.004),
                      (0.249, -0.0695, 0.003)], -0.019, 0.019, "rubber", bevel=0.002, segs=2)
    g = Group()
    g.side([(0.1, -0.004), (0.13, -0.008), (0.13, -0.016, 0.003), (0.104, -0.012, 0.003)], -0.006, 0.006)
    g.done("stock_lever", "poly", bevel=0.0007)
    g = Group()
    for sx in (-1, 1):
        g.side([(0.215, -0.044), (0.237, -0.06), (0.237, -0.066), (0.211, -0.048)], sx * 0.003, sx * 0.007)
    g.cyl((0.0, -0.058, 0.226), 0.0024, 0.016, axis="x", segs=12)
    g.done("sling_loop", "steel", bevel=0.0004)


def build():
    upper()
    lower()
    grip()
    controls()
    magazine()
    stock()
