"""3.5× 棱镜光学镜（Trijicon ACOG TA31 形态，×1.2）：锻铝镜体 + 物镜筒 + 目镜 +
顶部光纤导光条 + 平顶快拆座。"""
import gun_kit as K
from gun_kit import Group, side, xsec, lathe, box, cyl

META = dict(ref=(0.0, 0.0, 0.0), target=(0.0, 0.0, 0.0), length=None, size=1024)
AY = 0.052   # 光轴高


def build():
    # 镜体：物镜罩 → 方形棱镜仓 → 目镜
    lathe("objective", [(-0.205, 0.0262), (-0.2, 0.0275), (-0.17, 0.0275), (-0.15, 0.0235), (-0.13, 0.022)],
          "alu", cy=AY, segs=40)
    lathe("eyepiece", [(-0.07, 0.019), (-0.04, 0.0195), (-0.022, 0.0215), (-0.012, 0.0215), (-0.008, 0.019)],
          "alu", cy=AY, segs=40)
    side("housing", [(-0.14, AY - 0.024), (-0.06, AY - 0.024), (-0.055, AY - 0.012, 0.006), (-0.06, AY + 0.024, 0.008),
                     (-0.145, AY + 0.024, 0.008), (-0.15, AY, 0.006)], -0.0225, 0.0225, "alu", r=0.002, bevel=0.0025)
    # 顶部光纤导光条 + 两端座
    g = Group()
    g.box((0.0, AY + 0.0285, -0.1), (0.008, 0.005, 0.07))
    g.box((0.0, AY + 0.027, -0.135), (0.012, 0.006, 0.01))
    g.box((0.0, AY + 0.027, -0.066), (0.012, 0.006, 0.01))
    g.done("fiber_mount", "alu", bevel=0.0012)
    box("fiber", (0.0, AY + 0.0315, -0.1), (0.0045, 0.0018, 0.06), "bakelite", bevel=0.0006)
    # 高低/风偏调节帽
    cyl("elev_cap", (0.0, AY + 0.027, -0.09), 0.0075, 0.007, "alu", axis="y", segs=20)
    cyl("wind_cap", (0.0255, AY, -0.09), 0.0075, 0.007, "alu", axis="x", segs=20)
    # 镜片
    cyl("lens_front", (0.0, AY, -0.2045), 0.0238, 0.001, "lens", axis="z", segs=40, bevel=0.0)
    cyl("lens_rear", (0.0, AY, -0.0085), 0.0145, 0.001, "lens", axis="z", segs=32, bevel=0.0)
    # 平顶快拆座：底座夹爪 + 立板 + 左侧两枚拇指螺母
    g = Group()
    g.side([(-0.15, -0.0055), (-0.065, -0.0055), (-0.065, 0.006), (-0.15, 0.006)], -0.0215, 0.0215)
    g.side([(-0.145, 0.005), (-0.07, 0.005), (-0.072, AY - 0.022, 0.004), (-0.143, AY - 0.022, 0.004)], -0.014, 0.014)
    g.done("mount", "alu", bevel=0.0015)
    g = Group()
    for z in (-0.13, -0.085):
        g.lathe([(-0.0215, 0.0075), (-0.031, 0.0075), (-0.032, 0.006)], cx=0.0, cy=z, segs=12, axis="x")
    g.done("thumb_nuts", "steel", bevel=0.0006)
