def pchip(keys):
    """单调三次插值（Fritsch–Carlson）：keys[(t, v)] → f(t)，平段保持平、不过冲"""
    xs = [k[0] for k in keys]
    ys = [k[1] for k in keys]
    n = len(xs)
    h = [xs[i + 1] - xs[i] for i in range(n - 1)]
    d = [(ys[i + 1] - ys[i]) / h[i] for i in range(n - 1)]
    m = [0.0] * n
    m[0], m[-1] = d[0], d[-1]
    for i in range(1, n - 1):
        if d[i - 1] * d[i] <= 0:
            m[i] = 0.0
        else:
            w1, w2 = 2 * h[i] + h[i - 1], h[i] + 2 * h[i - 1]
            m[i] = (w1 + w2) / (w1 / d[i - 1] + w2 / d[i])

    def f(x):
        if x <= xs[0]:
            return ys[0]
        if x >= xs[-1]:
            return ys[-1]
        i = bisect_right(xs, x) - 1
        t = (x - xs[i]) / h[i]
        t2, t3 = t * t, t * t * t
        return ((2 * t3 - 3 * t2 + 1) * ys[i] + (t3 - 2 * t2 + t) * h[i] * m[i]
                + (-2 * t3 + 3 * t2) * ys[i + 1] + (t3 - t2) * h[i] * m[i + 1])
    return f


def _sg(v):
    return 1.0 if v >= 0 else -1.0


def superel(hw, yt, ym, yb, et=3.0, eb=3.0, wt=1.0, wb=1.0, n=28, xc=0.0):
    """圆角截面（逆时针）：上半 ym→yt 指数 et，下半 ym→yb 指数 eb；wt/wb 上/下半收窄"""
    pts = []
    for k in range(n):
        t = 2 * math.pi * k / n
        c, s = math.cos(t), math.sin(t)
        if s >= 0:
            e, hh = et, yt - ym
        else:
            e, hh = eb, ym - yb
        x = hw * _sg(c) * abs(c) ** (2.0 / e)
        y = ym + hh * _sg(s) * abs(s) ** (2.0 / e)
        x *= 1 + (wt - 1) * max(s, 0.0) + (wb - 1) * max(-s, 0.0)
        pts.append((xc + x, y))
    return pts


def loft_bm(bm, secs, cap0=True, cap1=True):
    """放样：secs[(z, [(x, y)...])] 各截面点数相同，逐段连四边形，两端封面"""
    rings = [[bm.verts.new(K.B(x, y, z)) for x, y in pts] for z, pts in secs]
    n = len(rings[0])
    for i in range(len(rings) - 1):
        r0, r1 = rings[i], rings[i + 1]
        for j in range(n):
            j2 = (j + 1) % n
            bm.faces.new((r0[j], r0[j2], r1[j2], r1[j]))
    if cap0:
        bm.faces.new(rings[0][::-1])
    if cap1:
        bm.faces.new(rings[-1])


def loft(name, secs, zone, **kw):
    bm = bmesh.new()
    loft_bm(bm, secs, **{k: kw.pop(k) for k in ("cap0", "cap1") if k in kw})
    return K.obj(name, bm, zone, **kw)


def revolve_bm(bm, prof, cx=0.0, cy=0.0, segs=32):
    """闭环回转体（管、环）：prof 为 (z, r) 闭合环，首尾相连、不封面"""
    rings = []
    for z, r in prof:
        rings.append([bm.verts.new(K.B(cx + r * math.cos(2 * math.pi * j / segs),
                                       cy + r * math.sin(2 * math.pi * j / segs), z)) for j in range(segs)])
    n = len(rings)
    for i in range(n):
        r0, r1 = rings[i], rings[(i + 1) % n]
        for j in range(segs):
            j2 = (j + 1) % segs
            bm.faces.new((r0[j], r0[j2], r1[j2], r1[j]))


def torus_bm(bm, c, R, r, axis="x", segs=20, rsegs=8):
    """圆环（背带环）：axis 为环轴"""
    rings = []
    for i in range(segs):
        a = 2 * math.pi * i / segs
        ring = []
        for j in range(rsegs):
            b = 2 * math.pi * j / rsegs
            rr = R + r * math.cos(b)
            u, v, w = rr * math.cos(a), rr * math.sin(a), r * math.sin(b)
            if axis == "x":
                p = (c[0] + w, c[1] + u, c[2] + v)
            elif axis == "y":
                p = (c[0] + u, c[1] + w, c[2] + v)
            else:
                p = (c[0] + u, c[1] + v, c[2] + w)
            ring.append(bm.verts.new(K.B(*p)))
        rings.append(ring)
    for i in range(segs):
        r0, r1 = rings[i], rings[(i + 1) % segs]
        for j in range(rsegs):
            j2 = (j + 1) % rsegs
            bm.faces.new((r0[j], r0[j2], r1[j2], r1[j]))


def gear_pts(cz, cy, r, teeth, depth=0.0006):
    """滚花旋钮侧轮廓（z, y）：齿顶 r、齿根 r-depth"""
    pts = []
    for k in range(teeth * 2):
        a = math.pi * k / teeth
        rr = r if k % 2 == 0 else r - depth
        pts.append((cz + rr * math.cos(a), cy + rr * math.sin(a)))
    return pts


def sector(r0, r1, a0, a1, n=6, cy=0.0):
    """环扇形截面（x, y）：角度制 a0→a1"""
    out = [(r1 * math.cos(math.radians(a0 + (a1 - a0) * k / n)),
            cy + r1 * math.sin(math.radians(a0 + (a1 - a0) * k / n))) for k in range(n + 1)]
    inn = [(r0 * math.cos(math.radians(a1 - (a1 - a0) * k / n)),
            cy + r0 * math.sin(math.radians(a1 - (a1 - a0) * k / n))) for k in range(n + 1)]
    return out + inn


